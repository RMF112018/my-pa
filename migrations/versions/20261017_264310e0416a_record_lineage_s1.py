#: Section 4.1, `project_situations`: refuse, before any foreign key is added,
#: while an existing row names another Principal's Project or Situation. The
#: message carries the two counts and no identifier; nothing is repaired.
_PROJECT_SITUATION_PREFLIGHT: Final = """
    DO $$
    DECLARE
      foreign_projects bigint;
      foreign_situations bigint;
    BEGIN
      SELECT count(*) INTO foreign_projects
        FROM knowledge.project_situations ps
        JOIN knowledge.projects p ON p.project_id = ps.project_id
       WHERE p.principal_id <> ps.principal_id;
      SELECT count(*) INTO foreign_situations
        FROM knowledge.project_situations ps
        JOIN knowledge.situations s ON s.situation_id = ps.situation_id
       WHERE s.principal_id <> ps.principal_id;
      IF foreign_projects > 0 OR foreign_situations > 0 THEN
        RAISE EXCEPTION 'project_situations names another principal (% project, % situation)',
          foreign_projects, foreign_situations
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """

