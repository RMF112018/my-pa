#: `downgrade` refuses while any of these holds, rather than deleting user data
#: to make the downgrade pass (section 4.3).
_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.issue_revision_evidence)
         OR EXISTS (SELECT 1 FROM knowledge.issue_responsibility_events)
         OR EXISTS (SELECT 1 FROM knowledge.lineage_write_request_links)
         OR EXISTS (
           SELECT 1 FROM knowledge.issue_revisions
            WHERE action IN ('closed', 'corrected', 'reopened') OR state = 'closed'
         )
         OR EXISTS (
           SELECT 1 FROM knowledge.record_links
            WHERE relation_type IN (
                    'blocks', 'created_to_resolve', 'delegated_from', 'escalated_from'
                  )
               OR source_capability IN (
                    'issues.work.create_commitment', 'issues.work.create_task'
                  )
         )
         OR EXISTS (
           SELECT 1 FROM knowledge.record_link_revisions
            WHERE source_capability IN (
                    'issues.memberships.correct', 'issues.work.create_commitment',
                    'issues.work.create_task'
                  )
               OR member_native_version IS NOT NULL
         )
         OR EXISTS (
           SELECT 1 FROM knowledge.lineage_write_requests
            WHERE capability IN (
                    'issues.close', 'issues.handoffs.record', 'issues.memberships.correct',
                    'issues.reopen', 'issues.work.create_commitment', 'issues.work.create_task'
                  )
         )
         OR EXISTS (
           SELECT 1 FROM knowledge.audit_events
           WHERE capability IN (
                   'issues.close', 'issues.closure_readiness', 'issues.handoffs.list',
                   'issues.handoffs.record', 'issues.memberships.correct', 'issues.reopen',
                   'issues.work.create_commitment', 'issues.work.create_task'
                 )
              OR purpose IN ('issue_work_authoring')
         ) THEN
        RAISE EXCEPTION 'record lineage S2 rows exist; refusing to downgrade d020b532ad7d'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def _restate_audit(capability: str, purpose: str) -> None:
    for name, expression in (("capability_is_known", capability), ("purpose_is_known", purpose)):
        op.drop_constraint(name, "audit_events", schema=SCHEMA, type_="check")
        op.create_check_constraint(name, "audit_events", expression, schema=SCHEMA)


def _restate_check(table: str, name: str, expression: str) -> None:
    op.execute(f"ALTER TABLE {SCHEMA}.{table} DROP CONSTRAINT {name}")
    op.execute(f"ALTER TABLE {SCHEMA}.{table} ADD CONSTRAINT {name} CHECK ({expression})")


def _checks_on(table: str) -> None:
    for widened_table, name, _before, after in _WIDENED_CHECKS:
        if widened_table == table:
            _restate_check(table, name, after)
    for added_table, name, expression in _ADDED_CHECKS:
        if added_table == table:
            op.execute(f"ALTER TABLE {SCHEMA}.{table} ADD CONSTRAINT {name} CHECK ({expression})")


def upgrade() -> None:
    for statement in _ISSUE_REVISION_COLUMNS:
        op.execute(statement)
    _checks_on("issue_revisions")
    _checks_on("record_links")
    for statement in _RECORD_LINK_REVISION_COLUMNS:
        op.execute(statement)
    _checks_on("record_link_revisions")
    for _table, ddl in _TABLE_DDL:
        op.execute(ddl)
    for statement in _WRITE_REQUEST_COLUMNS:
        op.execute(statement)
    _checks_on("lineage_write_requests")
    op.execute(_WRITE_REQUEST_HANDOFF_FOREIGN_KEY)
    for _name, definition in _FUNCTIONS:
        op.execute(definition)
    for _name, definition, _previous in _REPLACED_FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)
    _restate_audit(_CAPABILITIES_AT_THIS_REVISION, _PURPOSES_AT_THIS_REVISION)


def downgrade() -> None:
    op.execute(_REFUSE_DOWNGRADE)
    _restate_audit(_CAPABILITIES_BEFORE_THIS_REVISION, _PURPOSES_BEFORE_THIS_REVISION)
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for _name, _definition, previous in reversed(_REPLACED_FUNCTIONS):
        op.execute(previous)
    for name, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}()")
    op.execute(
        f"ALTER TABLE {SCHEMA}.lineage_write_requests DROP CONSTRAINT "
        "a_lineage_write_request_names_a_handoff"
    )
    for table in (
        "lineage_write_requests",
        "record_link_revisions",
        "record_links",
        "issue_revisions",
    ):
        for added_table, name, _expression in reversed(_ADDED_CHECKS):
            if added_table == table:
                op.execute(f"ALTER TABLE {SCHEMA}.{table} DROP CONSTRAINT {name}")
        for widened_table, name, before, _after in reversed(_WIDENED_CHECKS):
            if widened_table == table:
                _restate_check(table, name, before)
        if table == "lineage_write_requests":
            for column in ("result_record_id", "result_record_family", "result_handoff_id"):
                op.execute(f"ALTER TABLE {SCHEMA}.lineage_write_requests DROP COLUMN {column}")
            for name, _ddl in reversed(_TABLE_DDL):
                op.execute(f"DROP TABLE {SCHEMA}.{name} RESTRICT")
        elif table == "record_link_revisions":
            op.execute(
                f"ALTER TABLE {SCHEMA}.record_link_revisions DROP COLUMN member_native_version"
            )
        elif table == "issue_revisions":
            for column in (
                "evidence_set_digest",
                "evidence_count",
                "reason",
                "outcome",
                "closed_at",
            ):
                op.execute(f"ALTER TABLE {SCHEMA}.issue_revisions DROP COLUMN {column}")
