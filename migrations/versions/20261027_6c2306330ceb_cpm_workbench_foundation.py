#: The three append-only tables: `(trigger, table)`.
_APPEND_ONLY: Final = (
    ("schedule_series_are_append_only", "schedule_series"),
    ("schedule_activities_are_append_only", "schedule_activities"),
    ("schedule_import_issues_are_append_only", "schedule_import_issues"),
)

#: All seven tables. A TRUNCATE is refused only while the table holds a row,
#: so a fixture's `TRUNCATE ... CASCADE` through an empty CPM table still
#: passes (the lineage precedent).
_TRUNCATE_REFUSALS: Final = (
    ("schedule_series_refuse_truncate", "schedule_series"),
    ("schedule_publications_refuse_truncate", "schedule_publications"),
    ("schedule_activities_refuse_truncate", "schedule_activities"),
    ("schedule_jobs_refuse_truncate", "schedule_jobs"),
    ("schedule_parser_runs_refuse_truncate", "schedule_parser_runs"),
    ("schedule_rows_refuse_truncate", "schedule_rows"),
    ("schedule_import_issues_refuse_truncate", "schedule_import_issues"),
)

#: The row-level lifecycle guards: `(trigger = function, table, timing)`.
_LIFECYCLE: Final = (
    (
        "a_schedule_publication_follows_its_lifecycle",
        "schedule_publications",
        "BEFORE INSERT OR UPDATE OR DELETE",
    ),
    ("a_schedule_job_keeps_its_identity", "schedule_jobs", "BEFORE INSERT OR UPDATE OR DELETE"),
    (
        "a_schedule_parser_run_follows_its_lifecycle",
        "schedule_parser_runs",
        "BEFORE INSERT OR UPDATE OR DELETE",
    ),
    (
        "a_schedule_row_changes_only_by_linking",
        "schedule_rows",
        "BEFORE INSERT OR UPDATE OR DELETE",
    ),
    (
        "a_schedule_issue_is_recorded_while_processing",
        "schedule_import_issues",
        "BEFORE INSERT",
    ),
)


def _triggers() -> tuple[tuple[str, str, str], ...]:
    """Every trigger: `(name, table, definition)`, in creation order."""
    created: list[tuple[str, str, str]] = []
    for trigger, table in _APPEND_ONLY:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE UPDATE OR DELETE ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.schedule_relations_are_append_only()",
            )
        )
    for trigger, table in _TRUNCATE_REFUSALS:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE TRUNCATE ON {SCHEMA}.{table} "
                f"FOR EACH STATEMENT EXECUTE FUNCTION "
                f"{SCHEMA}.schedule_relations_refuse_truncate()",
            )
        )
    for trigger, table, timing in _LIFECYCLE:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} {timing} ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    created.append(
        (
            "a_schedule_publication_has_its_job",
            "schedule_publications",
            "CREATE CONSTRAINT TRIGGER a_schedule_publication_has_its_job AFTER INSERT ON "
            f"{SCHEMA}.schedule_publications DEFERRABLE INITIALLY DEFERRED FOR EACH ROW "
            f"EXECUTE FUNCTION {SCHEMA}.a_schedule_publication_has_its_job()",
        )
    )
    return tuple(created)


