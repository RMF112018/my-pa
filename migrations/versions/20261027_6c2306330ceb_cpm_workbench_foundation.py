#: Catalog-only preflight: both single-column primary keys still hold, so the
#: composite uniques cannot meet a duplicate. No row is scanned.
_PREFLIGHT: Final = """
    DO $$
    DECLARE
      target record;
    BEGIN
      FOR target IN
        SELECT * FROM (VALUES ('enrollments', 'enrollment_id'),
                              ('source_object_versions', 'version_id')) AS t(relation, key)
      LOOP
        IF NOT EXISTS (
          SELECT 1
            FROM pg_constraint c
            JOIN pg_class r ON r.oid = c.conrelid
            JOIN pg_namespace n ON n.oid = r.relnamespace
            JOIN pg_attribute a ON a.attrelid = r.oid AND a.attnum = c.conkey[1]
           WHERE n.nspname = 'knowledge' AND r.relname = target.relation
             AND c.contype = 'p' AND cardinality(c.conkey) = 1 AND a.attname = target.key
        ) THEN
          RAISE EXCEPTION
            'cpm workbench preflight: % no longer has its single-column primary key %',
            target.relation, target.key
            USING ERRCODE = 'restrict_violation';
        END IF;
      END LOOP;
    END $$
    """

