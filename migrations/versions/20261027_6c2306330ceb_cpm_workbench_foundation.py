_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.schedule_series)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_publications)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_activities)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_jobs)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_parser_runs)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_rows)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_import_issues) THEN
        RAISE EXCEPTION 'cpm workbench rows exist; refusing to downgrade 6c2306330ceb'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    for _table, ddl, indexes in _TABLES:
        op.execute(ddl)
        for index in indexes:
            op.execute(index)
    op.execute(_ACCEPTED_RUN[1])
    for _name, _signature, definition in _FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)
    op.execute(_PREFLIGHT)
    for table, name, columns in _SUPPORT_UNIQUES:
        op.execute(f"CREATE UNIQUE INDEX {name} ON {SCHEMA}.{table} ({columns})")
    for table, name, _columns in _SUPPORT_UNIQUES:
        op.execute(f"ALTER TABLE {SCHEMA}.{table} ADD CONSTRAINT {name} UNIQUE USING INDEX {name}")
    for table, name, definition in _LIVE_FOREIGN_KEYS:
        op.execute(f"ALTER TABLE {SCHEMA}.{table} ADD CONSTRAINT {name} {definition}")


def downgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_REFUSE_DOWNGRADE)
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for name, signature, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}({signature})")
    op.execute(f"ALTER TABLE {SCHEMA}.schedule_publications DROP CONSTRAINT {_ACCEPTED_RUN[0]}")
    for table, _ddl, _indexes in reversed(_TABLES):
        op.execute(f"DROP TABLE {SCHEMA}.{table} RESTRICT")
    for table, name, _columns in reversed(_SUPPORT_UNIQUES):
        op.execute(f"ALTER TABLE {SCHEMA}.{table} DROP CONSTRAINT {name}")
