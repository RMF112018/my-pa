#: `downgrade` refuses while any plane row, S6 lineage row or `approved_update`
#: publication exists, rather than deleting rows to make the downgrade pass.
#: Each clause alone suffices.
_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.schedule_intake_series)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_series_match_decisions)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_baselines)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_baseline_events)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_governing_events)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_scenarios)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_scenario_versions)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_cpm_runs)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_scenario_outputs)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_scenario_write_requests)
         OR EXISTS (SELECT 1 FROM knowledge.schedule_scenario_write_refusals)
         OR EXISTS (
           SELECT 1 FROM knowledge.record_links
            WHERE from_family IN ('scenario', 'scenario_output', 'scenario_version',
                                  'schedule_activity', 'schedule_baseline',
                                  'schedule_publication')
               OR to_family IN ('scenario', 'scenario_output', 'scenario_version',
                                'schedule_activity', 'schedule_baseline',
                                'schedule_publication')
               OR relation_type IN ('concerns', 'delays', 'mitigates'))
         OR EXISTS (
           SELECT 1 FROM knowledge.schedule_publications
            WHERE baseline_kind = 'approved_update') THEN
        RAISE EXCEPTION 'schedule scenarios rows exist; refusing to downgrade 2a90f91dd786'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def _restated(table: str, checks: tuple[tuple[str, str, str], ...], *, at: bool) -> str:
    """One multi-clause `ALTER TABLE`: every CHECK of `table` validated in one pass."""
    clauses = ", ".join(
        f"DROP CONSTRAINT {name}, ADD CONSTRAINT {name} CHECK ({after if at else before})"
        for name, before, after in checks
    )
    return f"ALTER TABLE {SCHEMA}.{table} {clauses}"


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_REFUSE_RETIRED_ROLES)
    for _table, ddl, indexes in _TABLES:
        op.execute(ddl)
        for index in indexes:
            op.execute(index)
    op.execute(_FORK[1])
    for _name, definition in _FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)
    # Live phase A: `schedule_publications`.
    op.execute(_LOCK_PUBLICATIONS)
    op.execute(_REFUSE_RETIRED_ROLES)
    op.execute(_restated("schedule_publications", _PUBLICATION_CHECKS, at=True))
    op.execute(_INTAKE_GUARD[1])
    # Live phase B: the foreign keys into the S5 tables.
    for table, name, definition in _LIVE_FOREIGN_KEYS:
        op.execute(f"ALTER TABLE {SCHEMA}.{table} ADD CONSTRAINT {name} {definition}")
    # Live phase C: `record_links`, last.
    op.execute(_restated("record_links", _RECORD_LINK_CHECKS, at=True))


def downgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_REFUSE_DOWNGRADE)
    op.execute(f"DROP TRIGGER {_INTAKE_GUARD[0]} ON {SCHEMA}.schedule_publications")
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for name, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}()")
    op.execute(f"ALTER TABLE {SCHEMA}.schedule_scenarios DROP CONSTRAINT {_FORK[0]}")
    for table, _ddl, _indexes in reversed(_TABLES):
        op.execute(f"DROP TABLE {SCHEMA}.{table} RESTRICT")
    op.execute(_restated("schedule_publications", _PUBLICATION_CHECKS, at=False))
    op.execute(_restated("record_links", _RECORD_LINK_CHECKS, at=False))
