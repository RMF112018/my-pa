def _id(column: str, prefix: str) -> str:
    return (
        f"CONSTRAINT {column}_is_an_opaque_identifier CHECK ({column} ~ "
        f"'^{prefix}_[A-Za-z0-9]{{8,64}}$')"
    )


def _sha(column: str, name: str) -> str:
    return f"CONSTRAINT {name} CHECK ({column} ~ '^[0-9a-f]{{64}}$')"


def _name(column: str) -> str:
    """Section 14.3 `N(col)`."""
