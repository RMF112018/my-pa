#: `downgrade` refuses while any plane row exists, or any audit event names a
#: capability or the purpose step 6 admits, rather than deleting rows or audit
#: history to make the downgrade pass. Each clause alone suffices.
_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.report_content_objects)
         OR EXISTS (SELECT 1 FROM knowledge.report_roots)
         OR EXISTS (SELECT 1 FROM knowledge.report_versions)
         OR EXISTS (SELECT 1 FROM knowledge.report_version_manifests)
         OR EXISTS (SELECT 1 FROM knowledge.report_associations)
         OR EXISTS (SELECT 1 FROM knowledge.report_lifecycle_events)
         OR EXISTS (SELECT 1 FROM knowledge.report_receipts)
         OR EXISTS (SELECT 1 FROM knowledge.report_transfer_sessions)
         OR EXISTS (SELECT 1 FROM knowledge.report_transfer_chunks)
         OR EXISTS (SELECT 1 FROM knowledge.report_hold_events)
         OR EXISTS (SELECT 1 FROM knowledge.report_retention_policy_events) THEN
        RAISE EXCEPTION 'general report plane state exists; refusing to downgrade 4c37731671fc'
          USING ERRCODE = 'restrict_violation';
      END IF;
      IF EXISTS (
           SELECT 1 FROM knowledge.audit_events
            WHERE capability IN ('reports.archive', 'reports.delete', 'reports.history',
                                 'reports.hold.place', 'reports.hold.release',
                                 'reports.publish', 'reports.restore',
                                 'reports.retention.get', 'reports.retention.set',
                                 'reports.update')
               OR purpose IN ('report_hold', 'report_lifecycle', 'report_retention')) THEN
        RAISE EXCEPTION 'general report audit history exists; refusing to downgrade 4c37731671fc'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def _restate_audit(name: str, expression: str) -> None:
    op.drop_constraint(name, "audit_events", schema=SCHEMA, type_="check")
    op.create_check_constraint(name, "audit_events", expression, schema=SCHEMA)


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    for _table, ddl, indexes in _TABLES:
        op.execute(ddl)
        for index in indexes:
            op.execute(index)
    for name, definition in _DEFERRED_FOREIGN_KEYS:
        op.execute(f"ALTER TABLE {SCHEMA}.report_roots ADD CONSTRAINT {name} {definition}")
    for _name, definition in _FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)
    _restate_audit("capability_is_known", _CAPABILITIES_AT_THIS_REVISION)
    _restate_audit("purpose_is_known", _PURPOSES_AT_THIS_REVISION)


def downgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_LOCK_PLANE)
    op.execute(_REFUSE_DOWNGRADE)
    _restate_audit("capability_is_known", _CAPABILITIES_BEFORE_THIS_REVISION)
    _restate_audit("purpose_is_known", _PURPOSES_BEFORE_THIS_REVISION)
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for name, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}()")
    for name, _definition in reversed(_DEFERRED_FOREIGN_KEYS):
        op.execute(f"ALTER TABLE {SCHEMA}.report_roots DROP CONSTRAINT {name}")
    for table, _ddl, _indexes in reversed(_TABLES):
        op.execute(f"DROP TABLE {SCHEMA}.{table} RESTRICT")
