def _triggers() -> tuple[tuple[str, str, str], ...]:
    """Every trigger on the new tables: `(name, table, definition)`, in creation order."""
    created: list[tuple[str, str, str]] = []
    for table in _APPEND_ONLY:
        trigger = f"{table}_are_append_only"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE UPDATE OR DELETE ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.report_plane_rows_are_append_only()",
            )
        )
    for table in _TRUNCATE_REFUSALS:
        trigger = f"{table}_refuse_truncate"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE TRUNCATE ON {SCHEMA}.{table} "
                f"FOR EACH STATEMENT EXECUTE FUNCTION "
                f"{SCHEMA}.report_plane_relations_refuse_truncate()",
            )
        )
    for trigger, table, timing in _ROW_GUARDS:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} {timing} ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    for trigger, table in _WRITTEN_WITH_THEIR_VERSION:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE INSERT ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION "
                f"{SCHEMA}.report_rows_are_written_with_their_version()",
            )
        )
    for trigger, table, events in _DEFERRED:
        created.append(
            (
                trigger,
                table,
                f"CREATE CONSTRAINT TRIGGER {trigger} AFTER {events} ON {SCHEMA}.{table} "
                f"DEFERRABLE INITIALLY DEFERRED FOR EACH ROW "
                f"EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    return tuple(created)


# ---- downgrade -----------------------------------------------------------------------

#: `downgrade` locks the 8 plane tables before it checks them, so no plane row
#: can commit between the refusal check and the drops.
_LOCK_PLANE: Final = (
    "LOCK TABLE knowledge.report_content_objects, knowledge.report_roots, "
    "knowledge.report_versions, knowledge.report_version_manifests, "
    "knowledge.report_associations, knowledge.report_lifecycle_events, "
    "knowledge.report_receipts, knowledge.report_transfer_sessions IN ACCESS EXCLUSIVE MODE"
)

#: `downgrade` refuses while any plane row exists, rather than deleting rows to
#: make the downgrade pass. Each clause alone suffices.
_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.report_content_objects)
         OR EXISTS (SELECT 1 FROM knowledge.report_roots)
         OR EXISTS (SELECT 1 FROM knowledge.report_versions)
         OR EXISTS (SELECT 1 FROM knowledge.report_version_manifests)
         OR EXISTS (SELECT 1 FROM knowledge.report_associations)
         OR EXISTS (SELECT 1 FROM knowledge.report_lifecycle_events)
         OR EXISTS (SELECT 1 FROM knowledge.report_receipts)
         OR EXISTS (SELECT 1 FROM knowledge.report_transfer_sessions) THEN
        RAISE EXCEPTION 'general report plane state exists; refusing to downgrade 4c37731671fc'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    for _table, ddl, indexes in _TABLES:
        op.execute(ddl)
        for index in indexes:
            op.execute(index)
    for name, definition in _DEFERRED_FOREIGN_KEYS:
        op.execute(f"ALTER TABLE {SCHEMA}.report_roots ADD CONSTRAINT {name} {definition}")
    for _name, definition in _FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)


def downgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_LOCK_PLANE)
    op.execute(_REFUSE_DOWNGRADE)
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for name, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}()")
    for name, _definition in reversed(_DEFERRED_FOREIGN_KEYS):
        op.execute(f"ALTER TABLE {SCHEMA}.report_roots DROP CONSTRAINT {name}")
    for table, _ddl, _indexes in reversed(_TABLES):
        op.execute(f"DROP TABLE {SCHEMA}.{table} RESTRICT")
