#: The 9 append-only tables (every plane table but the root and the transfer
#: session, whose updates are guarded instead).
_APPEND_ONLY: Final = (
    "report_content_objects",
    "report_versions",
    "report_version_manifests",
    "report_associations",
    "report_lifecycle_events",
    "report_receipts",
    "report_hold_events",
    "report_retention_policy_events",
    "report_transfer_chunks",
)

#: All 11 tables. A TRUNCATE is refused only while the table holds a row, so a
#: fixture's `TRUNCATE ... CASCADE` through an empty plane table still passes.
_TRUNCATE_REFUSALS: Final = tuple(name for name, _ddl, _indexes in _TABLES)

#: The row-level guards: `(trigger = function, table, timing)`. A retention
#: event's previous period must equal its predecessor's period: a composite
#: reference over the nullable period columns would be `MATCH SIMPLE` and skip
#: every row whose old or new period is unset, so the equality is this
#: `BEFORE INSERT` guard, beside the reference on the non-null predecessor key.
#: The guard finds the predecessor by id and owner only (its revision is the
#: reference's and the CHECKs'), and refuses one it cannot see. A transfer
#: chunk (WP06 A2) continues its session: the session (by id and owner) is
#: visible and `open`, the chunk starts at the session's received byte count
#: and ends within its declaration; the repository inserts the chunk, then
#: advances `received_byte_count`.
_ROW_GUARDS: Final = (
    ("a_report_root_moves_only_its_caches", "report_roots", "BEFORE UPDATE OR DELETE"),
    (
        "a_report_transfer_session_moves_forward",
        "report_transfer_sessions",
        "BEFORE UPDATE OR DELETE",
    ),
    (
        "a_report_retention_event_continues_its_predecessor",
        "report_retention_policy_events",
        "BEFORE INSERT",
    ),
    (
        "a_report_transfer_chunk_continues_its_session",
        "report_transfer_chunks",
        "BEFORE INSERT",
    ),
)

#: The insert guards: `(trigger, table)`, each `BEFORE INSERT` and executing
#: `report_rows_are_written_with_their_version`. A manifest or an association
#: is written only in the transaction that writes its version.
_WRITTEN_WITH_THEIR_VERSION: Final = (
    ("a_report_manifest_is_written_with_its_version", "report_version_manifests"),
    ("a_report_association_is_written_with_its_version", "report_associations"),
)

#: The deferred commit checks: `(trigger = function, table, events)`. A new
#: version must have its manifest, and the root cache must name the newest
#: version, the newest lifecycle event and the newest hold event of its report,
#: when the transaction that writes them commits.
_DEFERRED: Final = (
    ("a_report_version_has_its_manifest", "report_versions", "INSERT"),
    ("a_report_head_is_its_newest_version", "report_versions", "INSERT"),
    ("a_report_lifecycle_cache_is_its_newest_event", "report_lifecycle_events", "INSERT"),
    ("a_report_hold_cache_is_its_newest_event", "report_hold_events", "INSERT"),
)


def _triggers() -> tuple[tuple[str, str, str], ...]:
    """Every trigger on the new tables: `(name, table, definition)`, in creation order."""
    created: list[tuple[str, str, str]] = []
    for table in _APPEND_ONLY:
        trigger = f"{table}_are_append_only"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE UPDATE OR DELETE ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.report_plane_rows_are_append_only()",
            )
        )
    for table in _TRUNCATE_REFUSALS:
        trigger = f"{table}_refuse_truncate"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE TRUNCATE ON {SCHEMA}.{table} "
                f"FOR EACH STATEMENT EXECUTE FUNCTION "
                f"{SCHEMA}.report_plane_relations_refuse_truncate()",
            )
        )
    for trigger, table, timing in _ROW_GUARDS:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} {timing} ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    for trigger, table in _WRITTEN_WITH_THEIR_VERSION:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE INSERT ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION "
                f"{SCHEMA}.report_rows_are_written_with_their_version()",
            )
        )
    for trigger, table, events in _DEFERRED:
        created.append(
            (
                trigger,
                table,
                f"CREATE CONSTRAINT TRIGGER {trigger} AFTER {events} ON {SCHEMA}.{table} "
                f"DEFERRABLE INITIALLY DEFERRED FOR EACH ROW "
                f"EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    return tuple(created)


