def _triggers() -> tuple[tuple[str, str, str], ...]:
    """Every trigger on the new tables: `(name, table, definition)`, in creation order."""
    created: list[tuple[str, str, str]] = []
    for table in _APPEND_ONLY:
        trigger = f"{table}_are_append_only"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE UPDATE OR DELETE ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.file_workspace_rows_are_append_only()",
            )
        )
    for table in _TRUNCATE_REFUSALS:
        trigger = f"{table}_refuse_truncate"
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} BEFORE TRUNCATE ON {SCHEMA}.{table} "
                f"FOR EACH STATEMENT EXECUTE FUNCTION "
                f"{SCHEMA}.file_workspace_relations_refuse_truncate()",
            )
        )
    for trigger, table, timing in _ROW_GUARDS:
        created.append(
            (
                trigger,
                table,
                f"CREATE TRIGGER {trigger} {timing} ON {SCHEMA}.{table} "
                f"FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.{trigger}()",
            )
        )
    return tuple(created)


# ---- downgrade -----------------------------------------------------------------------

#: `downgrade` locks the 4 plane tables and the audit table before it checks
#: them, so no plane row or audit event can commit between the refusal check and
#: the drops.
_LOCK_PLANE: Final = (
    "LOCK TABLE knowledge.file_workspace_transfers, knowledge.file_workspace_versions, "
    "knowledge.file_workspace_trash, knowledge.file_workspace_receipts, "
    "knowledge.audit_events IN ACCESS EXCLUSIVE MODE"
)

#: `downgrade` refuses while any plane row exists, or any audit event names a
#: capability or purpose step 4 admits, rather than deleting rows or audit
#: history to make the downgrade pass. Each clause alone suffices.
_REFUSE_DOWNGRADE: Final = """
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM knowledge.file_workspace_transfers)
         OR EXISTS (SELECT 1 FROM knowledge.file_workspace_versions)
         OR EXISTS (SELECT 1 FROM knowledge.file_workspace_trash)
         OR EXISTS (SELECT 1 FROM knowledge.file_workspace_receipts) THEN
        RAISE EXCEPTION 'files workspace state exists; refusing to downgrade 640aaacc78e8'
          USING ERRCODE = 'restrict_violation';
      END IF;
      IF EXISTS (
           SELECT 1 FROM knowledge.audit_events
            WHERE capability IN ('files.copy', 'files.download.begin', 'files.history',
                                 'files.list', 'files.mkdir', 'files.move', 'files.preview',
                                 'files.rename', 'files.restore', 'files.search',
                                 'files.stat', 'files.trash', 'files.upload.abort',
                                 'files.upload.begin', 'files.upload.finalize',
                                 'files.workspaces.list', 'files.write_text')
               OR purpose IN ('file_workspace_authoring', 'file_workspace_read')) THEN
        RAISE EXCEPTION 'files workspace audit history exists; refusing to downgrade 640aaacc78e8'
          USING ERRCODE = 'restrict_violation';
      END IF;
    END $$
    """


def _restate_audit(name: str, expression: str) -> None:
    op.drop_constraint(name, "audit_events", schema=SCHEMA, type_="check")
    op.create_check_constraint(name, "audit_events", expression, schema=SCHEMA)


def upgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    for _table, ddl, indexes in _TABLES:
        op.execute(ddl)
        for index in indexes:
            op.execute(index)
    for _name, definition in _FUNCTIONS:
        op.execute(definition)
    for _trigger, _table, definition in _triggers():
        op.execute(definition)
    _restate_audit("capability_is_known", _CAPABILITIES_AT_THIS_REVISION)
    _restate_audit("purpose_is_known", _PURPOSES_AT_THIS_REVISION)


def downgrade() -> None:
    op.execute(_LOCK_TIMEOUT)
    op.execute(_LOCK_PLANE)
    op.execute(_REFUSE_DOWNGRADE)
    _restate_audit("capability_is_known", _CAPABILITIES_BEFORE_THIS_REVISION)
    _restate_audit("purpose_is_known", _PURPOSES_BEFORE_THIS_REVISION)
    for trigger, table, _definition in reversed(_triggers()):
        op.execute(f"DROP TRIGGER {trigger} ON {SCHEMA}.{table}")
    for name, _definition in reversed(_FUNCTIONS):
        op.execute(f"DROP FUNCTION {SCHEMA}.{name}()")
    for table, _ddl, _indexes in reversed(_TABLES):
        op.execute(f"DROP TABLE {SCHEMA}.{table} RESTRICT")
