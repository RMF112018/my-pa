def _id(column: str, prefix: str) -> str:
    return (
        f"CONSTRAINT {column}_is_an_opaque_identifier CHECK ({column} ~ "
        f"'^{prefix}_[A-Za-z0-9]{{8,64}}$')"
    )


def _sha(column: str, name: str, *, nullable: bool = False) -> str:
    predicate = f"{column} ~ '^[0-9a-f]{{64}}$'"
    if nullable:
        predicate = f"{column} IS NULL OR {predicate}"
    return f"CONSTRAINT {name} CHECK ({predicate})"


def _version(column: str, name: str, *, nullable: bool = False) -> str:
    predicate = f"{column} ~ {_VERSION_TOKEN_PATTERN}"
    if nullable:
        predicate = f"{column} IS NULL OR {predicate}"
    return f"CONSTRAINT {name} CHECK ({predicate})"


def _path(column: str, name: str) -> str:
    return (
        f"CONSTRAINT {name} CHECK (octet_length({column}) BETWEEN 1 AND {_MAX_PATH_BYTES} "
        f"AND left({column}, 1) <> '/' AND right({column}, 1) <> '/')"
    )


