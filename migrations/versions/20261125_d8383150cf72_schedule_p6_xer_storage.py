def _typed(columns: tuple[tuple[str, str, bool, int | str | None], ...]) -> str:
    return "".join(
        f"\n      {name} {sql}{' NOT NULL' if not_null else ''},"
        for name, sql, not_null, _ in columns
    )


def _run_checks(short: str, columns: tuple[tuple[str, str, bool, int | str | None], ...]) -> str:
    """The identifier, line, text-bound and token CHECKs and the run foreign key."""
    checks = [
        _id("parser_run_id", "sprun"),
        _id("principal_id", "prn"),
        _id("publication_id", "spub"),
        f"CONSTRAINT a_p6_{short}_record_line_is_positive CHECK (record_line >= 1)",
    ]
    texts = [(name, bound) for name, _, _, bound in columns if isinstance(bound, int)]
    if texts:
        checks.append(
            f"CONSTRAINT a_p6_{short}_text_is_bounded CHECK ("
            + " AND ".join(
                f"({name} IS NULL OR char_length({name}) BETWEEN 1 AND {bound})"
                for name, bound in texts
            )
            + ")"
        )
    tokens = [name for name, _, _, bound in columns if bound == "token"]
    if tokens:
        checks.append(
            f"CONSTRAINT a_p6_{short}_enumeration_is_a_token CHECK ("
            + " AND ".join(f"({name} IS NULL OR {name} ~ {_TOKEN})" for name in tokens)
            + ")"
        )
    checks.append(
        f"CONSTRAINT a_p6_{short}_belongs_to_its_run FOREIGN KEY(parser_run_id, "
        "publication_id, principal_id) REFERENCES knowledge.schedule_parser_runs "
        "(parser_run_id, publication_id, principal_id) ON DELETE RESTRICT"
    )
    return ",\n      ".join(checks)


