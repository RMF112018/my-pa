"""S7-0: the MY-PA standard calendar `my-pa-us-40h-v1` (import contract section 11.6).

Contract: `docs/architecture/schedule-xer-import-contract.md` section 11.6. The
default calendar wherever a source gives none. It is a versioned constant of
the scenario domain, generated by **rule**, never from a list of years:

* week: Monday to Friday, one interval `[480, 960]` (08:00-16:00); weekend off;
* holidays: the 11 US federal holidays (Juneteenth from 2021, the year it
  became one); a fixed-date holiday on a Saturday is observed the Friday
  before, on a Sunday the Monday after (New Year's Day on a Saturday falls on
  31 December of the previous year); an observed date outside
  2000-01-01..2099-12-31 is dropped;
* materialization: the holidays of the years `data_date.year - 2` to
  `data_date.year + 20`, clipped to 2000..2099 (at most 253 dates), each an
  exception with no interval;
* a variant workday (`standard_workday`) is keyed `my-pa-us-40h-v1-<HHMM...>`
  so 2 variants never share a key.

A change of any rule is a new key (`-v2`); stored content keeps the old
calendar's materialized data. Pure and standard-library only: no clock,
randomness, environment or IO.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import date, timedelta
from enum import StrEnum
from typing import Final, NamedTuple

from my_pa.domain.schedule.scenario.model import (
    MAX_INTERVALS_PER_DAY,
    MINUTES_PER_DAY,
    CalendarException,
    DayPattern,
    ScenarioCalendar,
    ScenarioContent,
    is_calendar_key,
)

__all__ = [
    "FIRST_HOLIDAY_YEAR",
    "HORIZON_YEARS_AFTER",
    "HORIZON_YEARS_BEFORE",
    "JUNETEENTH_FIRST_YEAR",
    "LAST_HOLIDAY_YEAR",
    "STANDARD_CALENDAR_KEY",
    "STANDARD_WORKDAY",
    "FederalHoliday",
    "ObservedHoliday",
    "federal_holidays",
    "is_standard_calendar_key",
    "materialized_years",
    "standard_calendar",
    "standard_calendar_horizon_exceeded",
    "standard_calendar_key",
]

STANDARD_CALENDAR_KEY: Final = "my-pa-us-40h-v1"
#: The one working interval of a standard working day: 08:00-16:00.
STANDARD_WORKDAY: Final[DayPattern] = ((480, 960),)
#: The rule window: an observed date outside it is dropped.
FIRST_HOLIDAY_YEAR: Final = 2000
LAST_HOLIDAY_YEAR: Final = 2099
_FIRST_DAY: Final = date(FIRST_HOLIDAY_YEAR, 1, 1)
_LAST_DAY: Final = date(LAST_HOLIDAY_YEAR, 12, 31)
JUNETEENTH_FIRST_YEAR: Final = 2021
HORIZON_YEARS_BEFORE: Final = 2
HORIZON_YEARS_AFTER: Final = 20
_MONDAY: Final = 0
_THURSDAY: Final = 3
_SATURDAY: Final = 5
_SUNDAY: Final = 6


class FederalHoliday(StrEnum):
    """The 11 US federal holidays, in calendar order."""

    NEW_YEARS_DAY = "new_years_day"
    MARTIN_LUTHER_KING_JR_DAY = "martin_luther_king_jr_day"
    PRESIDENTS_DAY = "presidents_day"
    MEMORIAL_DAY = "memorial_day"
    JUNETEENTH = "juneteenth"
    INDEPENDENCE_DAY = "independence_day"
    LABOR_DAY = "labor_day"
    COLUMBUS_DAY = "columbus_day"
    VETERANS_DAY = "veterans_day"
    THANKSGIVING_DAY = "thanksgiving_day"
    CHRISTMAS_DAY = "christmas_day"


#: Fixed-date holidays (month, day); the observed rule applies to these only.
_FIXED: Final[dict[FederalHoliday, tuple[int, int]]] = {
    FederalHoliday.NEW_YEARS_DAY: (1, 1),
    FederalHoliday.JUNETEENTH: (6, 19),
    FederalHoliday.INDEPENDENCE_DAY: (7, 4),
    FederalHoliday.VETERANS_DAY: (11, 11),
    FederalHoliday.CHRISTMAS_DAY: (12, 25),
}
#: Nth-weekday holidays (month, weekday, n); n = -1 is the last one of the month.
_NTH: Final[dict[FederalHoliday, tuple[int, int, int]]] = {
    FederalHoliday.MARTIN_LUTHER_KING_JR_DAY: (1, _MONDAY, 3),
    FederalHoliday.PRESIDENTS_DAY: (2, _MONDAY, 3),
    FederalHoliday.MEMORIAL_DAY: (5, _MONDAY, -1),
    FederalHoliday.LABOR_DAY: (9, _MONDAY, 1),
    FederalHoliday.COLUMBUS_DAY: (10, _MONDAY, 2),
    FederalHoliday.THANKSGIVING_DAY: (11, _THURSDAY, 4),
}


class ObservedHoliday(NamedTuple):
    """The holiday of `year` and its observed (non-working) day."""

    holiday: FederalHoliday
    year: int
    observed: date


def _nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    if n > 0:
        first = date(year, month, 1)
        return first + timedelta(days=(weekday - first.weekday()) % 7 + 7 * (n - 1))
    following = date(year + 1, 1, 1) if month == 12 else date(year, month + 1, 1)
    last = following - timedelta(days=1)
    return last - timedelta(days=(last.weekday() - weekday) % 7)


def _observed(day: date) -> date:
    """Saturday -> the Friday before; Sunday -> the Monday after; else the day."""
    if day.weekday() == _SATURDAY:
        return day - timedelta(days=1)
    if day.weekday() == _SUNDAY:
        return day + timedelta(days=1)
    return day


def federal_holidays(year: int) -> tuple[ObservedHoliday, ...]:
    """The observed federal holidays of `year` (2000..2099), in calendar order.

    Juneteenth exists from 2021. An observed date outside 2000-01-01..2099-12-31
    is dropped (1 Jan 2000 is a Saturday: its observed day is 31 Dec 1999).
    """
    if type(year) is not int or not FIRST_HOLIDAY_YEAR <= year <= LAST_HOLIDAY_YEAR:
        raise ValueError("a holiday year lies in 2000..2099")
    found: list[ObservedHoliday] = []
    for holiday in FederalHoliday:
        if holiday is FederalHoliday.JUNETEENTH and year < JUNETEENTH_FIRST_YEAR:
            continue
        if holiday in _FIXED:
            month, day = _FIXED[holiday]
            observed = _observed(date(year, month, day))
        else:
            month, weekday, n = _NTH[holiday]
            observed = _nth_weekday(year, month, weekday, n)
        if _FIRST_DAY <= observed <= _LAST_DAY:
            found.append(ObservedHoliday(holiday, year, observed))
    return tuple(sorted(found, key=lambda item: item.observed))


def materialized_years(data_date_year: int) -> range:
    """`data_date.year - 2 .. data_date.year + 20`, clipped to 2000..2099."""
    if type(data_date_year) is not int:
        raise ValueError("a data date year is an integer")
    first = max(FIRST_HOLIDAY_YEAR, data_date_year - HORIZON_YEARS_BEFORE)
    last = min(LAST_HOLIDAY_YEAR, data_date_year + HORIZON_YEARS_AFTER)
    return range(first, last + 1)


def _hhmm(minute: int) -> str:
    hours, minutes = divmod(minute, 60)
    return f"{hours:02d}{minutes:02d}"


def _workday(workday: Sequence[Sequence[int]]) -> DayPattern:
    pattern: DayPattern = tuple((interval[0], interval[1]) for interval in workday)
    if not 1 <= len(pattern) <= MAX_INTERVALS_PER_DAY:
        raise ValueError("a standard workday has 1..4 intervals")
    previous_end = -1
    for start, end in pattern:
        if type(start) is not int or type(end) is not int:
            raise ValueError("a standard workday interval is integer minutes")
        if not 0 <= start < end <= MINUTES_PER_DAY or start <= previous_end:
            raise ValueError("a standard workday has sorted, separated intervals in a day")
        previous_end = end
    return pattern


def standard_calendar_key(workday: Sequence[Sequence[int]] = STANDARD_WORKDAY) -> str:
    """`my-pa-us-40h-v1`, or `my-pa-us-40h-v1-<start><end>...` for a variant workday.

    Each interval contributes its start and end as `HHMM` (`24:00` is `2400`),
    for example `((420, 930),)` -> `my-pa-us-40h-v1-07001530`. A calendar key
    is at most 32 characters, so a variant has at most 2 intervals; a longer
    one is refused (`ValueError`).
    """
    pattern = _workday(workday)
    if pattern == STANDARD_WORKDAY:
        return STANDARD_CALENDAR_KEY
    key = STANDARD_CALENDAR_KEY + "-" + "".join(_hhmm(s) + _hhmm(e) for s, e in pattern)
    if not is_calendar_key(key):
        raise ValueError("a standard workday variant key is at most 32 characters")
    return key


def is_standard_calendar_key(value: object) -> bool:
    """The standard calendar's key or one of its variant keys."""
    return isinstance(value, str) and (
        value == STANDARD_CALENDAR_KEY or value.startswith(STANDARD_CALENDAR_KEY + "-")
    )


def standard_calendar(
    data_date_year: int, workday: Sequence[Sequence[int]] = STANDARD_WORKDAY
) -> ScenarioCalendar:
    """The standard calendar materialized for a data date in `data_date_year`."""
    pattern = _workday(workday)
    key = standard_calendar_key(pattern)
    exceptions = tuple(
        CalendarException(day=item.observed, intervals=())
        for year in materialized_years(data_date_year)
        for item in federal_holidays(year)
    )
    return ScenarioCalendar(key=key, week=(pattern,) * 5 + ((), ()), exceptions=exceptions)


def _first_missing_holiday(calendar: ScenarioCalendar, from_year: int, to_year: int) -> date | None:
    non_working = {item.day for item in calendar.exceptions if not item.intervals}
    for year in range(max(FIRST_HOLIDAY_YEAR, from_year), min(LAST_HOLIDAY_YEAR, to_year) + 1):
        for item in federal_holidays(year):
            if item.observed not in non_working:
                return item.observed
    return None


def standard_calendar_horizon_exceeded(
    content: ScenarioContent, latest_instant: int
) -> tuple[str, ...]:
    """Section 11.6: the standard calendars a run reaching `latest_instant` outruns.

    A standard calendar (its key or a variant's) is outrun when some observed
    federal holiday from the data date's year to `latest_instant`'s year is not
    a non-working exception of it and starts before `latest_instant`: the run
    then crossed a day the rule makes a holiday but the materialized calendar
    does not (`standard_calendar_horizon_exceeded`). The client may extend the
    calendar with `calendar.exception.put`. Keys in key order.
    """
    start_year = (_FIRST_DAY + timedelta(days=content.data_date // MINUTES_PER_DAY)).year
    last_year = (_FIRST_DAY + timedelta(days=latest_instant // MINUTES_PER_DAY)).year
    outrun: list[str] = []
    for calendar in content.calendars:
        if not is_standard_calendar_key(calendar.key):
            continue
        missing = _first_missing_holiday(calendar, start_year, last_year)
        if missing is None:
            continue
        missing_start = (missing - _FIRST_DAY).days * MINUTES_PER_DAY
        if missing_start < latest_instant:
            outrun.append(calendar.key)
    return tuple(outrun)
