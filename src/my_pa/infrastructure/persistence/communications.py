"""The communications tables, behind `contracts.ports.CommunicationsRepository` (WP3a).

Six tables are reached here and nowhere else: `communication_messages`,
`communication_mailbox_items`, `communication_observations`,
`communication_participants`, `communication_identifiers` and
`communication_quarantine` (contract sections 5.1 and 5.2, revision
`52a829ef718a`). No statement reads or writes `search_document`: it is
generated by the server from `subject` and `search_text`.

**The partition is reached through the guard, never written by hand.** The
`persistence/meetings.py` idiom: every SELECT and UPDATE composes `_mine` (a
one-line wrapper over `partition_criterion`), every INSERT composes `_bound` (a
one-line wrapper over `principal_bound_values`), and the one join (a provider
id's item to its message) composes `matching_partition_criterion`.

**Only the projection moves.** The revision's trigger refuses an UPDATE of any
column but the projection group, `latest_snapshot_id`, the three flags and (since
`fa18ef3d9bc0`) `source_unavailable` and `identifiers_version`; the update
methods here name only those columns. A provider id is matched, never
rekeyed (Manager ruling M6): there is no method that changes an item.

**The operator aggregate.** `communications_aggregate` is the one read outside
the port: counts over the rows a set of ingest sources' snapshots produced, for
the operator CLI's `aggregate` (the real-corpus check of contract section 20.3).
It scopes by the sources' `ingest_snapshots`, which is the one table it reads
beyond the six, and returns counts and closed codes only -- never a subject, an
address, a provider id, an identifier value or a row id.
"""

