def _projection_values(projection: CommunicationProjection) -> dict[str, object]:
    return {
        "body_state": projection.body_state,
        "body_sha256": projection.body_sha256,
        "body_utf8_bytes": projection.body_utf8_bytes,
        "content_type": projection.content_type,
        "search_text": projection.search_text,
        "search_text_sha256": projection.search_text_sha256,
        "search_text_version": projection.search_text_version,
        "search_text_basis": projection.search_text_basis,
        "search_text_flags": sorted(projection.search_text_flags),
        "text_snapshot_id": projection.text_snapshot_id,
        "text_record_ordinal": projection.text_record_ordinal,
    }


def _to_message(row: Row[Any]) -> CommunicationMessageRecord:
    return CommunicationMessageRecord(
        message_id=row.message_id,
        mailbox_ref=row.mailbox_ref,
        identity_kind=row.identity_kind,
        identity_value=row.identity_value,
        conversation_id=row.conversation_id,
        subject=row.subject,
        sender_address=row.sender_address,
        message_time=row.message_time,
        message_time_basis=row.message_time_basis,
        has_attachments=row.has_attachments,
        projection=CommunicationProjection(
            body_state=row.body_state,
            body_sha256=row.body_sha256,
            body_utf8_bytes=row.body_utf8_bytes,
            content_type=row.content_type,
            search_text=row.search_text,
            search_text_sha256=row.search_text_sha256,
            search_text_version=row.search_text_version,
            search_text_basis=row.search_text_basis,
            search_text_flags=tuple(row.search_text_flags),
            text_snapshot_id=row.text_snapshot_id,
            text_record_ordinal=row.text_record_ordinal,
        ),
        first_snapshot_id=row.first_snapshot_id,
        latest_snapshot_id=row.latest_snapshot_id,
        identity_conflict=row.identity_conflict,
        participants_reconciled=row.participants_reconciled,
        participants_disagreed=row.participants_disagreed,
    )


def _to_item(row: Row[Any]) -> CommunicationMailboxItemRecord:
    return CommunicationMailboxItemRecord(
        item_id=row.item_id,
        message_id=row.message_id,
        mailbox_ref=row.mailbox_ref,
        provider_id=row.provider_id,
        provider_id_format=row.provider_id_format,
        first_snapshot_id=row.first_snapshot_id,
    )


def _participants_json(participants: Mapping[str, Sequence[str]]) -> dict[str, list[str]]:
    return {field: list(addresses) for field, addresses in sorted(participants.items())}


def _to_observation(row: Row[Any]) -> CommunicationObservationRecord:
    return CommunicationObservationRecord(
        observation_id=row.observation_id,
        item_id=row.item_id,
        snapshot_id=row.snapshot_id,
        record_ordinal=row.record_ordinal,
        classification=row.classification,
        reasons=tuple(row.reasons),
        folder_role=row.folder_role,
        lane_verification=row.lane_verification,
        selected_field=row.selected_field,
        selected_utc=row.selected_utc,
        received_utc=row.received_utc,
        received_state=row.received_state,
        sent_utc=row.sent_utc,
        sent_state=row.sent_state,
        body_sha256=row.body_sha256,
        unique_body_sha256=row.unique_body_sha256,
        participants={
            str(field): tuple(addresses) for field, addresses in dict(row.participants).items()
        },
    )


class SqlCommunicationsRepository(CommunicationsRepository):
    """`CommunicationsRepository`, over the general unit of work's `Connection`.

    Takes the connection rather than opening one: the caller owns the
    transaction, and this class only issues statements on it. Nothing here
    commits.
    """

    def __init__(self, connection: Connection) -> None:
        self._connection = connection

    # --- messages ------------------------------------------------------------

    def _message(
        self, statement: Select[Any], *, for_update: bool
    ) -> CommunicationMessageRecord | None:
        if for_update:
            statement = statement.with_for_update(of=communication_messages)
        row = self._connection.execute(statement).one_or_none()
        return None if row is None else _to_message(row)

    def get_message(
        self, principal_id: str, message_id: str, *, for_update: bool = False
    ) -> CommunicationMessageRecord | None:
        return self._message(
            select(*_MESSAGE_COLUMNS).where(
                _mine(communication_messages, principal_id),
                communication_messages.c.message_id == message_id,
            ),
            for_update=for_update,
        )

    def find_message_by_identity(
        self,
        principal_id: str,
        mailbox_ref: str,
        identity_kind: str,
        identity_value: str,
        *,
        for_update: bool = False,
    ) -> CommunicationMessageRecord | None:
        return self._message(
            select(*_MESSAGE_COLUMNS).where(
                _mine(communication_messages, principal_id),
                communication_messages.c.mailbox_ref == mailbox_ref,
                communication_messages.c.identity_kind == identity_kind,
                communication_messages.c.identity_value == identity_value,
            ),
            for_update=for_update,
        )

    def find_item_by_provider_id(
        self, principal_id: str, mailbox_ref: str, provider_id: str
    ) -> CommunicationMailboxItemRecord | None:
        row = self._connection.execute(
            select(*_ITEM_COLUMNS).where(
                _mine(communication_mailbox_items, principal_id),
                communication_mailbox_items.c.mailbox_ref == mailbox_ref,
                communication_mailbox_items.c.provider_id == provider_id,
            )
        ).one_or_none()
        return None if row is None else _to_item(row)

    def find_message_by_provider_id(
        self,
        principal_id: str,
        mailbox_ref: str,
        provider_id: str,
        *,
        for_update: bool = False,
    ) -> CommunicationMessageRecord | None:
        items = communication_mailbox_items
        return self._message(
            select(*_MESSAGE_COLUMNS)
            .join(
                items,
                matching_partition_criterion(items, communication_messages)
                & (items.c.message_id == communication_messages.c.message_id),
            )
            .where(
                _mine(communication_messages, principal_id),
                items.c.mailbox_ref == mailbox_ref,
                items.c.provider_id == provider_id,
            ),
            for_update=for_update,
        )

    def list_items(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationMailboxItemRecord, ...]:
        rows = self._connection.execute(
            select(*_ITEM_COLUMNS)
            .where(
                _mine(communication_mailbox_items, principal_id),
                communication_mailbox_items.c.message_id == message_id,
            )
            .order_by(communication_mailbox_items.c.item_id)
        )
        return tuple(_to_item(row) for row in rows)

    def insert_message(self, principal_id: str, message: CommunicationMessageRecord) -> None:
        self._connection.execute(
            insert(communication_messages).values(
                _bound(
                    communication_messages,
                    principal_id,
                    {
                        "message_id": message.message_id,
                        "mailbox_ref": message.mailbox_ref,
                        "identity_kind": message.identity_kind,
                        "identity_value": message.identity_value,
                        "conversation_id": message.conversation_id,
                        "subject": message.subject,
                        "sender_address": message.sender_address,
                        "message_time": message.message_time,
                        "message_time_basis": message.message_time_basis,
                        "has_attachments": message.has_attachments,
                        **_projection_values(message.projection),
                        "first_snapshot_id": message.first_snapshot_id,
                        "latest_snapshot_id": message.latest_snapshot_id,
                        "identity_conflict": message.identity_conflict,
                        "participants_reconciled": message.participants_reconciled,
                        "participants_disagreed": message.participants_disagreed,
                    },
                )
            )
        )

    def _update_message(
        self, principal_id: str, message_id: str, values: dict[str, object]
    ) -> None:
        changed = self._connection.execute(
            update(communication_messages)
            .where(
                _mine(communication_messages, principal_id),
                communication_messages.c.message_id == message_id,
            )
            .values(values)
            .returning(communication_messages.c.message_id)
        ).first()
        if changed is None:
            raise RepositoryFailureError

    def update_message_projection(
        self,
        principal_id: str,
        message_id: str,
        *,
        projection: CommunicationProjection,
        latest_snapshot_id: str,
    ) -> None:
        self._update_message(
            principal_id,
            message_id,
            {**_projection_values(projection), "latest_snapshot_id": latest_snapshot_id},
        )

    def set_latest_snapshot(self, principal_id: str, message_id: str, snapshot_id: str) -> None:
        self._update_message(principal_id, message_id, {"latest_snapshot_id": snapshot_id})

    def set_message_flags(
        self,
        principal_id: str,
        message_id: str,
        *,
        identity_conflict: bool | None = None,
        participants_reconciled: bool | None = None,
        participants_disagreed: bool | None = None,
    ) -> None:
        values: dict[str, object] = {
            name: value
            for name, value in (
                ("identity_conflict", identity_conflict),
                ("participants_reconciled", participants_reconciled),
                ("participants_disagreed", participants_disagreed),
            )
            if value is not None
        }
        if not values:
            raise ValueError("set_message_flags names no flag")
        self._update_message(principal_id, message_id, values)

    # --- items, observations, quarantine -------------------------------------

    def insert_item(self, principal_id: str, item: CommunicationMailboxItemRecord) -> None:
        self._connection.execute(
            insert(communication_mailbox_items).values(
                _bound(
                    communication_mailbox_items,
                    principal_id,
                    {
                        "item_id": item.item_id,
                        "message_id": item.message_id,
                        "mailbox_ref": item.mailbox_ref,
                        "provider_id": item.provider_id,
                        "provider_id_format": item.provider_id_format,
                        "first_snapshot_id": item.first_snapshot_id,
                    },
                )
            )
        )

    def insert_observation(
        self, principal_id: str, observation: CommunicationObservationRecord
    ) -> None:
        self._connection.execute(
            insert(communication_observations).values(
                _bound(
                    communication_observations,
                    principal_id,
                    {
                        "observation_id": observation.observation_id,
                        "item_id": observation.item_id,
                        "snapshot_id": observation.snapshot_id,
                        "record_ordinal": observation.record_ordinal,
                        "classification": observation.classification,
                        "reasons": sorted(observation.reasons),
                        "folder_role": observation.folder_role,
                        "lane_verification": observation.lane_verification,
                        "selected_field": observation.selected_field,
                        "selected_utc": observation.selected_utc,
                        "received_utc": observation.received_utc,
                        "received_state": observation.received_state,
                        "sent_utc": observation.sent_utc,
                        "sent_state": observation.sent_state,
                        "body_sha256": observation.body_sha256,
                        "unique_body_sha256": observation.unique_body_sha256,
                        "participants": _participants_json(observation.participants),
                    },
                )
            )
        )

    def insert_quarantine(
        self, principal_id: str, quarantine: CommunicationQuarantineRecord
    ) -> None:
        self._connection.execute(
            insert(communication_quarantine).values(
                _bound(
                    communication_quarantine,
                    principal_id,
                    {
                        "quarantine_id": quarantine.quarantine_id,
                        "snapshot_id": quarantine.snapshot_id,
                        "record_ordinal": quarantine.record_ordinal,
                        "reasons": sorted(quarantine.reasons),
                    },
                )
            )
        )

    def list_observations(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationObservationRecord, ...]:
        items = communication_mailbox_items
        rows = self._connection.execute(
            select(*_OBSERVATION_COLUMNS)
            .join(
                items,
                matching_partition_criterion(items, communication_observations)
                & (items.c.item_id == communication_observations.c.item_id),
            )
            .where(
                _mine(communication_observations, principal_id),
                items.c.message_id == message_id,
            )
            .order_by(
                communication_observations.c.snapshot_id,
                communication_observations.c.record_ordinal,
            )
        )
        return tuple(_to_observation(row) for row in rows)

    def tally_snapshot(self, principal_id: str, snapshot_id: str) -> CommunicationSnapshotTally:
        observations = self._connection.execute(
            select(func.count()).where(
                _mine(communication_observations, principal_id),
                communication_observations.c.snapshot_id == snapshot_id,
            )
        ).scalar_one()
        quarantined = self._connection.execute(
            select(func.count()).where(
                _mine(communication_quarantine, principal_id),
                communication_quarantine.c.snapshot_id == snapshot_id,
            )
        ).scalar_one()
        return CommunicationSnapshotTally(observations=observations, quarantined=quarantined)

    # --- participants and identifiers (set-like) -------------------------------

    def insert_participants(
        self, principal_id: str, participants: Sequence[CommunicationParticipantRecord]
    ) -> int:
        if not participants:
            return 0
        table = communication_participants
        inserted = self._connection.execute(
            pg_insert(table)
            .values(
                [
                    _bound(
                        table,
                        principal_id,
                        {
                            "message_id": participant.message_id,
                            "field": participant.field,
                            "address": participant.address,
                            "first_observation_id": participant.first_observation_id,
                        },
                    )
                    for participant in participants
                ]
            )
            .on_conflict_do_nothing(constraint="communication_participants_pkey")
            .returning(table.c.address)
        ).all()
        return len(inserted)

    def list_participants(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationParticipantRecord, ...]:
        table = communication_participants
        rows = self._connection.execute(
            select(table.c.message_id, table.c.field, table.c.address, table.c.first_observation_id)
            .where(_mine(table, principal_id), table.c.message_id == message_id)
            .order_by(table.c.field, table.c.address)
        )
        return tuple(
            CommunicationParticipantRecord(
                message_id=row.message_id,
                field=row.field,
                address=row.address,
                first_observation_id=row.first_observation_id,
            )
            for row in rows
        )

    def insert_identifiers(
        self, principal_id: str, identifiers: Sequence[CommunicationIdentifierRecord]
    ) -> int:
        if not identifiers:
            return 0
        table = communication_identifiers
        inserted = self._connection.execute(
            pg_insert(table)
            .values(
                [
                    _bound(
                        table,
                        principal_id,
                        {
                            "message_id": identifier.message_id,
                            "kind": identifier.kind,
                            "value": identifier.value,
                            "extractor_version": identifier.extractor_version,
                        },
                    )
                    for identifier in identifiers
                ]
            )
            .on_conflict_do_nothing(constraint="communication_identifiers_pkey")
            .returning(table.c.value)
        ).all()
        return len(inserted)

    def list_identifiers(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationIdentifierRecord, ...]:
        table = communication_identifiers
        rows = self._connection.execute(
            select(table.c.message_id, table.c.kind, table.c.value, table.c.extractor_version)
            .where(_mine(table, principal_id), table.c.message_id == message_id)
            .order_by(table.c.extractor_version, table.c.kind, table.c.value)
        )
        return tuple(
            CommunicationIdentifierRecord(
                message_id=row.message_id,
                kind=row.kind,
                value=row.value,
                extractor_version=row.extractor_version,
            )
            for row in rows
        )
