class SqlCommunicationsRepository(CommunicationsRepository):
    """`CommunicationsRepository`, over the general unit of work's `Connection`.

    Takes the connection rather than opening one: the caller owns the
    transaction, and this class only issues statements on it. Nothing here
    commits.
    """

    def __init__(self, connection: Connection) -> None:
        self._connection = connection

    # --- messages ------------------------------------------------------------

    def _message(
        self, statement: Select[Any], *, for_update: bool
    ) -> CommunicationMessageRecord | None:
        if for_update:
            statement = statement.with_for_update(of=communication_messages)
        row = self._connection.execute(statement).one_or_none()
        return None if row is None else _to_message(row)

    def get_message(
        self, principal_id: str, message_id: str, *, for_update: bool = False
    ) -> CommunicationMessageRecord | None:
        return self._message(
            select(*_MESSAGE_COLUMNS).where(
                _mine(communication_messages, principal_id),
                communication_messages.c.message_id == message_id,
            ),
            for_update=for_update,
        )

    def find_message_by_identity(
        self,
        principal_id: str,
        mailbox_ref: str,
        identity_kind: str,
        identity_value: str,
        *,
        for_update: bool = False,
    ) -> CommunicationMessageRecord | None:
        return self._message(
            select(*_MESSAGE_COLUMNS).where(
                _mine(communication_messages, principal_id),
                communication_messages.c.mailbox_ref == mailbox_ref,
                communication_messages.c.identity_kind == identity_kind,
                communication_messages.c.identity_value == identity_value,
            ),
            for_update=for_update,
        )

    def find_item_by_provider_id(
        self, principal_id: str, mailbox_ref: str, provider_id: str
    ) -> CommunicationMailboxItemRecord | None:
        row = self._connection.execute(
            select(*_ITEM_COLUMNS).where(
                _mine(communication_mailbox_items, principal_id),
                communication_mailbox_items.c.mailbox_ref == mailbox_ref,
                communication_mailbox_items.c.provider_id == provider_id,
            )
        ).one_or_none()
        return None if row is None else _to_item(row)

    def find_message_by_provider_id(
        self,
        principal_id: str,
        mailbox_ref: str,
        provider_id: str,
        *,
        for_update: bool = False,
    ) -> CommunicationMessageRecord | None:
        items = communication_mailbox_items
        return self._message(
            select(*_MESSAGE_COLUMNS)
            .join(
                items,
                matching_partition_criterion(items, communication_messages)
                & (items.c.message_id == communication_messages.c.message_id),
            )
            .where(
                _mine(communication_messages, principal_id),
                items.c.mailbox_ref == mailbox_ref,
                items.c.provider_id == provider_id,
            ),
            for_update=for_update,
        )

    def list_items(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationMailboxItemRecord, ...]:
        rows = self._connection.execute(
            select(*_ITEM_COLUMNS)
            .where(
                _mine(communication_mailbox_items, principal_id),
                communication_mailbox_items.c.message_id == message_id,
            )
            .order_by(communication_mailbox_items.c.item_id)
        )
        return tuple(_to_item(row) for row in rows)

    def insert_message(self, principal_id: str, message: CommunicationMessageRecord) -> None:
        self._connection.execute(
            insert(communication_messages).values(
                _bound(
                    communication_messages,
                    principal_id,
                    {
                        "message_id": message.message_id,
                        "mailbox_ref": message.mailbox_ref,
                        "identity_kind": message.identity_kind,
                        "identity_value": message.identity_value,
                        "conversation_id": message.conversation_id,
                        "subject": message.subject,
                        "sender_address": message.sender_address,
                        "message_time": message.message_time,
                        "message_time_basis": message.message_time_basis,
                        "has_attachments": message.has_attachments,
                        **_projection_values(message.projection),
                        "first_snapshot_id": message.first_snapshot_id,
                        "latest_snapshot_id": message.latest_snapshot_id,
                        "identity_conflict": message.identity_conflict,
                        "participants_reconciled": message.participants_reconciled,
                        "participants_disagreed": message.participants_disagreed,
                        "source_unavailable": message.source_unavailable,
                        "identifiers_version": message.identifiers_version,
                    },
                )
            )
        )

    def _update_message(
        self, principal_id: str, message_id: str, values: dict[str, object]
    ) -> None:
        changed = self._connection.execute(
            update(communication_messages)
            .where(
                _mine(communication_messages, principal_id),
                communication_messages.c.message_id == message_id,
            )
            .values(values)
            .returning(communication_messages.c.message_id)
        ).first()
        if changed is None:
            raise RepositoryFailureError

    def update_message_projection(
        self,
        principal_id: str,
        message_id: str,
        *,
        projection: CommunicationProjection,
        latest_snapshot_id: str,
    ) -> None:
        self._update_message(
            principal_id,
            message_id,
            {**_projection_values(projection), "latest_snapshot_id": latest_snapshot_id},
        )

    def set_latest_snapshot(self, principal_id: str, message_id: str, snapshot_id: str) -> None:
        self._update_message(principal_id, message_id, {"latest_snapshot_id": snapshot_id})

    def set_message_flags(
        self,
        principal_id: str,
        message_id: str,
        *,
        identity_conflict: bool | None = None,
        participants_reconciled: bool | None = None,
        participants_disagreed: bool | None = None,
    ) -> None:
        values: dict[str, object] = {
            name: value
            for name, value in (
                ("identity_conflict", identity_conflict),
                ("participants_reconciled", participants_reconciled),
                ("participants_disagreed", participants_disagreed),
            )
            if value is not None
        }
        if not values:
            raise ValueError("set_message_flags names no flag")
        self._update_message(principal_id, message_id, values)

    def set_source_unavailable(
        self, principal_id: str, message_id: str, *, source_unavailable: bool
    ) -> None:
        self._update_message(principal_id, message_id, {"source_unavailable": source_unavailable})

    def set_identifiers_version(self, principal_id: str, message_id: str, version: str) -> None:
        self._update_message(principal_id, message_id, {"identifiers_version": version})

    # --- items, observations, quarantine -------------------------------------

    def insert_item(self, principal_id: str, item: CommunicationMailboxItemRecord) -> None:
        self._connection.execute(
            insert(communication_mailbox_items).values(
                _bound(
                    communication_mailbox_items,
                    principal_id,
                    {
                        "item_id": item.item_id,
                        "message_id": item.message_id,
                        "mailbox_ref": item.mailbox_ref,
                        "provider_id": item.provider_id,
                        "provider_id_format": item.provider_id_format,
                        "first_snapshot_id": item.first_snapshot_id,
                    },
                )
            )
        )

    def insert_observation(
        self, principal_id: str, observation: CommunicationObservationRecord
    ) -> None:
        self._connection.execute(
            insert(communication_observations).values(
                _bound(
                    communication_observations,
                    principal_id,
                    {
                        "observation_id": observation.observation_id,
                        "item_id": observation.item_id,
                        "snapshot_id": observation.snapshot_id,
                        "record_ordinal": observation.record_ordinal,
                        "classification": observation.classification,
                        "reasons": sorted(observation.reasons),
                        "folder_role": observation.folder_role,
                        "lane_verification": observation.lane_verification,
                        "selected_field": observation.selected_field,
                        "selected_utc": observation.selected_utc,
                        "received_utc": observation.received_utc,
                        "received_state": observation.received_state,
                        "sent_utc": observation.sent_utc,
                        "sent_state": observation.sent_state,
                        "body_sha256": observation.body_sha256,
                        "unique_body_sha256": observation.unique_body_sha256,
                        "participants": _participants_json(observation.participants),
                    },
                )
            )
        )

    def insert_quarantine(
        self, principal_id: str, quarantine: CommunicationQuarantineRecord
    ) -> None:
        self._connection.execute(
            insert(communication_quarantine).values(
                _bound(
                    communication_quarantine,
                    principal_id,
                    {
                        "quarantine_id": quarantine.quarantine_id,
                        "snapshot_id": quarantine.snapshot_id,
                        "record_ordinal": quarantine.record_ordinal,
                        "reasons": sorted(quarantine.reasons),
                    },
                )
            )
        )

    def list_observations(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationObservationRecord, ...]:
        items = communication_mailbox_items
        rows = self._connection.execute(
            select(*_OBSERVATION_COLUMNS)
            .join(
                items,
                matching_partition_criterion(items, communication_observations)
                & (items.c.item_id == communication_observations.c.item_id),
            )
            .where(
                _mine(communication_observations, principal_id),
                items.c.message_id == message_id,
            )
            .order_by(
                communication_observations.c.snapshot_id,
                communication_observations.c.record_ordinal,
            )
        )
        return tuple(_to_observation(row) for row in rows)

    def tally_snapshot(self, principal_id: str, snapshot_id: str) -> CommunicationSnapshotTally:
        observations = self._connection.execute(
            select(func.count()).where(
                _mine(communication_observations, principal_id),
                communication_observations.c.snapshot_id == snapshot_id,
            )
        ).scalar_one()
        quarantined = self._connection.execute(
            select(func.count()).where(
                _mine(communication_quarantine, principal_id),
                communication_quarantine.c.snapshot_id == snapshot_id,
            )
        ).scalar_one()
        return CommunicationSnapshotTally(observations=observations, quarantined=quarantined)

    # --- participants and identifiers (set-like) -------------------------------

    def insert_participants(
        self, principal_id: str, participants: Sequence[CommunicationParticipantRecord]
    ) -> int:
        if not participants:
            return 0
        table = communication_participants
        inserted = self._connection.execute(
            pg_insert(table)
            .values(
                [
                    _bound(
                        table,
                        principal_id,
                        {
                            "message_id": participant.message_id,
                            "field": participant.field,
                            "address": participant.address,
                            "first_observation_id": participant.first_observation_id,
                        },
                    )
                    for participant in participants
                ]
            )
            .on_conflict_do_nothing(constraint="communication_participants_pkey")
            .returning(table.c.address)
        ).all()
        return len(inserted)

    def list_participants(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationParticipantRecord, ...]:
        table = communication_participants
        rows = self._connection.execute(
            select(table.c.message_id, table.c.field, table.c.address, table.c.first_observation_id)
            .where(_mine(table, principal_id), table.c.message_id == message_id)
            .order_by(table.c.field, table.c.address)
        )
        return tuple(
            CommunicationParticipantRecord(
                message_id=row.message_id,
                field=row.field,
                address=row.address,
                first_observation_id=row.first_observation_id,
            )
            for row in rows
        )

    def insert_identifiers(
        self, principal_id: str, identifiers: Sequence[CommunicationIdentifierRecord]
    ) -> int:
        if not identifiers:
            return 0
        table = communication_identifiers
        inserted = self._connection.execute(
            pg_insert(table)
            .values(
                [
                    _bound(
                        table,
                        principal_id,
                        {
                            "message_id": identifier.message_id,
                            "kind": identifier.kind,
                            "value": identifier.value,
                            "extractor_version": identifier.extractor_version,
                        },
                    )
                    for identifier in identifiers
                ]
            )
            .on_conflict_do_nothing(constraint="communication_identifiers_pkey")
            .returning(table.c.value)
        ).all()
        return len(inserted)

    def list_identifiers(
        self, principal_id: str, message_id: str
    ) -> tuple[CommunicationIdentifierRecord, ...]:
        table = communication_identifiers
        rows = self._connection.execute(
            select(table.c.message_id, table.c.kind, table.c.value, table.c.extractor_version)
            .where(_mine(table, principal_id), table.c.message_id == message_id)
            .order_by(table.c.extractor_version, table.c.kind, table.c.value)
        )
        return tuple(
            CommunicationIdentifierRecord(
                message_id=row.message_id,
                kind=row.kind,
                value=row.value,
                extractor_version=row.extractor_version,
            )
            for row in rows
        )

    # --- the rederive's due set (WP4 ruling D2) -------------------------------

    def list_rederive_due(
        self,
        principal_id: str,
        *,
        search_text_version: str,
        identifiers_version: str,
        ingest_source_id: str | None = None,
        limit: int,
    ) -> tuple[CommunicationMessageRecord, ...]:
        rows = self._connection.execute(
            select(*_MESSAGE_COLUMNS)
            .where(
                *_rederive_due(
                    principal_id, search_text_version, identifiers_version, ingest_source_id
                )
            )
            .order_by(communication_messages.c.message_id)
            .limit(limit)
        )
        return tuple(_to_message(row) for row in rows)

    def count_rederive_due(
        self,
        principal_id: str,
        *,
        search_text_version: str,
        identifiers_version: str,
        ingest_source_id: str | None = None,
    ) -> int:
        return int(
            self._connection.execute(
                select(func.count()).where(
                    *_rederive_due(
                        principal_id, search_text_version, identifiers_version, ingest_source_id
                    )
                )
            ).scalar_one()
        )


def _source_snapshots(principal_id: str, ingest_source_ids: Sequence[str]) -> ScalarSelect[str]:
    """The snapshot ids of the given sources, as a scalar subquery."""
    return (
        select(ingest_snapshots.c.snapshot_id)
        .where(
            _mine(ingest_snapshots, principal_id),
            ingest_snapshots.c.ingest_source_id.in_(sorted(set(ingest_source_ids))),
        )
        .scalar_subquery()
    )


def _rederive_due(
    principal_id: str,
    search_text_version: str,
    identifiers_version: str,
    ingest_source_id: str | None,
) -> tuple[ColumnElement[bool], ...]:
    messages = communication_messages
    criteria: tuple[ColumnElement[bool], ...] = (
        _mine(messages, principal_id),
        or_(
            messages.c.search_text_version != search_text_version,
            messages.c.identifiers_version.is_distinct_from(identifiers_version),
            messages.c.source_unavailable.is_(True),
        ),
    )
    if ingest_source_id is not None:
        criteria += (
            messages.c.text_snapshot_id.in_(_source_snapshots(principal_id, [ingest_source_id])),
        )
    return criteria


def _counts(rows: Result[Any]) -> dict[str, int]:
    return {str(code): int(count) for code, count in rows}


def communications_aggregate(
    connection: Connection, principal_id: str, ingest_source_ids: Sequence[str]
) -> dict[str, object]:
    """Counts over what `ingest_source_ids`' snapshots produced (module docstring).

    * `observations` -- total, by classification, folder role and lane
      verification (one row per accepted record of an ingested snapshot);
    * `quarantined_records` and `quarantine_reasons` (one count per reason);
    * `items` and `messages` -- distinct mailbox items and canonical messages
      the scoped observations reach;
    * `multi_lane_item_snapshots` -- (item, snapshot) pairs with more than one
      observation, which is the per-publication `multi_lane` item count of the
      WP1 aggregate summed over publications; `multi_lane_items` the distinct
      items among them;
    * `messages_identity_conflict` -- scoped messages flagged `identity_conflict`;
    * `identifiers` -- per extractor version, then per kind, stored identifier
      rows and distinct messages. Versions are kept apart because the rows of
      every version stay side by side (the table is append-only, WP4 ruling R4),
      so a kind's count summed over versions would count one message twice.
    """
    ids = sorted(set(ingest_source_ids))
    observations = communication_observations
    items = communication_mailbox_items
    messages = communication_messages
    snapshots = (
        select(ingest_snapshots.c.snapshot_id)
        .where(
            _mine(ingest_snapshots, principal_id),
            ingest_snapshots.c.ingest_source_id.in_(ids),
        )
        .scalar_subquery()
    )
    scoped = (_mine(observations, principal_id), observations.c.snapshot_id.in_(snapshots))

    def grouped(column: ColumnElement[Any], *where: ColumnElement[bool]) -> dict[str, int]:
        return _counts(
            connection.execute(
                select(column, func.count()).where(*where).group_by(column).order_by(column)
            )
        )

    total = connection.execute(select(func.count()).where(*scoped)).scalar_one()
    item_ids = select(observations.c.item_id).where(*scoped).distinct().subquery()
    message_ids = (
        select(items.c.message_id)
        .where(
            _mine(items, principal_id),
            items.c.item_id.in_(select(item_ids.c.item_id)),
        )
        .distinct()
        .subquery()
    )
    pairs = (
        select(observations.c.item_id)
        .where(*scoped)
        .group_by(observations.c.item_id, observations.c.snapshot_id)
        .having(func.count() > 1)
        .subquery()
    )
    quarantine_scope = (
        _mine(communication_quarantine, principal_id),
        communication_quarantine.c.snapshot_id.in_(snapshots),
    )
    reasons = (
        select(func.unnest(communication_quarantine.c.reasons).label("reason"))
        .where(*quarantine_scope)
        .subquery()
    )
    identifier_scope = (
        _mine(communication_identifiers, principal_id),
        communication_identifiers.c.message_id.in_(select(message_ids.c.message_id)),
    )
    version, kind = communication_identifiers.c.extractor_version, communication_identifiers.c.kind
    identifiers: dict[str, dict[str, dict[str, int]]] = {}
    for extractor_version, identifier_kind, rows, distinct in connection.execute(
        select(
            version,
            kind,
            func.count(),
            func.count(func.distinct(communication_identifiers.c.message_id)),
        )
        .where(*identifier_scope)
        .group_by(version, kind)
        .order_by(version, kind)
    ):
        identifiers.setdefault(str(extractor_version), {})[str(identifier_kind)] = {
            "rows": int(rows),
            "messages": int(distinct),
        }
    return {
        "observations": {
            "total": int(total),
            "by_classification": grouped(observations.c.classification, *scoped),
            "by_folder_role": grouped(observations.c.folder_role, *scoped),
            "by_lane_verification": grouped(observations.c.lane_verification, *scoped),
        },
        "quarantined_records": int(
            connection.execute(select(func.count()).where(*quarantine_scope)).scalar_one()
        ),
        "quarantine_reasons": _counts(
            connection.execute(
                select(reasons.c.reason, func.count())
                .group_by(reasons.c.reason)
                .order_by(reasons.c.reason)
            )
        ),
        "items": int(connection.execute(select(func.count()).select_from(item_ids)).scalar_one()),
        "messages": int(
            connection.execute(select(func.count()).select_from(message_ids)).scalar_one()
        ),
        "multi_lane_item_snapshots": int(
            connection.execute(select(func.count()).select_from(pairs)).scalar_one()
        ),
        "multi_lane_items": int(
            connection.execute(select(func.count(func.distinct(pairs.c.item_id)))).scalar_one()
        ),
        "messages_identity_conflict": int(
            connection.execute(
                select(func.count()).where(
                    _mine(messages, principal_id),
                    messages.c.message_id.in_(select(message_ids.c.message_id)),
                    messages.c.identity_conflict.is_(True),
                )
            ).scalar_one()
        ),
        "identifiers": identifiers,
    }


# --- the english-against-simple measurement (WP4 ruling D4, report section 2.4) ---

#: The classes of probe term `communications_fts_measurement` forms per message.
FTS_PROBE_CLASSES: Final = ("identifier", "name")
#: The counts of each class, always present.
FTS_COUNT_KEYS: Final = (
    "probes",
    "present",
    "english_hit_of_present",
    "simple_hit_of_present",
    "english_miss_simple_hit",
    "english_miss_covered_by_identifier",
    "english_miss_uncovered",
    "stopword_empty",
)
#: `english_miss_uncovered` is material for a class above this share of its
#: present probes (the D4 decision rule; the Manager reads the counts too).
FTS_MATERIAL_SHARE: Final = 0.01
_ENGLISH: Final[ColumnElement[Any]] = literal_column("'english'::regconfig")
_SIMPLE: Final[ColumnElement[Any]] = literal_column("'simple'::regconfig")
_BARE_KINDS: Final = ("gmp", "fpl")


def _measured_ids(
    connection: Connection,
    scope: tuple[ColumnElement[bool], ...],
    after: str,
    limit: int | None,
) -> list[str]:
    messages = communication_messages
    statement = (
        select(messages.c.message_id)
        .where(*scope, messages.c.message_id > after)
        .order_by(messages.c.message_id)
    )
    if limit is not None:
        statement = statement.limit(limit)
    return [str(row) for row in connection.execute(statement).scalars()]


def _probe_counts(
    connection: Connection, principal_id: str, identifiers_version: str, ids: Sequence[str]
) -> dict[str, dict[str, int]]:
    """One batch's counts per probe class (`communications_fts_measurement`)."""
    messages = communication_messages
    identifiers = communication_identifiers
    participants = communication_participants
    surface = case(
        (identifiers.c.kind.in_(_BARE_KINDS), func.upper(identifiers.c.kind)),
        (identifiers.c.kind == "submittal", func.concat("Submittal ", identifiers.c.value)),
        (identifiers.c.kind == "spec", identifiers.c.value),
        else_=func.concat(func.upper(identifiers.c.kind), " ", identifiers.c.value),
    )
    identifier_probes = select(
        identifiers.c.message_id.label("message_id"),
        literal("identifier").label("cls"),
        surface.label("term"),
        literal(True).label("covered"),
    ).where(
        _mine(identifiers, principal_id),
        identifiers.c.extractor_version == identifiers_version,
        identifiers.c.message_id.in_(ids),
    )
    tokens = (
        select(
            participants.c.message_id.label("message_id"),
            func.unnest(
                func.regexp_split_to_array(
                    func.lower(func.split_part(participants.c.address, "@", 1)), "[^a-z]+"
                )
            ).label("token"),
        )
        .where(_mine(participants, principal_id), participants.c.message_id.in_(ids))
        .subquery("tokens")
    )
    name_probes = (
        select(
            tokens.c.message_id,
            literal("name").label("cls"),
            tokens.c.token.label("term"),
            literal(False).label("covered"),
        )
        .where(func.length(tokens.c.token) >= 3)
        .distinct()
    )
    probes = union_all(identifier_probes, name_probes).subquery("probes")
    body = func.concat(func.coalesce(messages.c.subject, ""), " ", messages.c.search_text)
    english_query = func.websearch_to_tsquery(_ENGLISH, probes.c.term)
    present = func.strpos(func.lower(body), func.lower(probes.c.term)) > 0
    english = messages.c.search_document.bool_op("@@")(english_query)
    simple = func.to_tsvector(_SIMPLE, body).bool_op("@@")(
        func.websearch_to_tsquery(_SIMPLE, probes.c.term)
    )
    english_miss = and_(present, not_(english))
    filters: dict[str, ColumnElement[bool] | None] = {
        "probes": None,
        "present": present,
        "english_hit_of_present": and_(present, english),
        "simple_hit_of_present": and_(present, simple),
        "english_miss_simple_hit": and_(english_miss, simple),
        "english_miss_covered_by_identifier": and_(english_miss, probes.c.covered.is_(True)),
        "english_miss_uncovered": and_(english_miss, probes.c.covered.is_(False)),
        "stopword_empty": and_(present, func.numnode(english_query) == 0),
    }
    rows = connection.execute(
        select(
            probes.c.cls,
            *(
                (func.count() if where is None else func.count().filter(where)).label(name)
                for name, where in filters.items()
            ),
        )
        .select_from(
            probes.join(
                messages,
                and_(
                    _mine(messages, principal_id),
                    messages.c.message_id == probes.c.message_id,
                ),
            )
        )
        .group_by(probes.c.cls)
    )
    return {
        str(row.cls): {name: int(row._mapping[name]) for name in FTS_COUNT_KEYS} for row in rows
    }


def communications_fts_measurement(
    connection: Connection,
    principal_id: str,
    *,
    identifiers_version: str,
    ingest_source_id: str | None = None,
    limit: int,
    batch_size: int = 500,
) -> dict[str, object]:
    """Counts only: `english` against `simple` over stored messages (report section 2.4).

    For each stored message with text (scoped to one source's snapshots by its
    text pointer when `ingest_source_id` is given), in `message_id` keyset
    batches of `batch_size`, at most `limit` messages, it forms probe terms:

    * `identifier` -- the surface form of each of its `identifiers_version`
      rows (`RFI 174`, `Submittal 033000-01`, `GMP`); the identifier index
      answers these, so an `english` miss is `english_miss_covered_by_identifier`;
    * `name` -- the alphabetic components of three characters or more of its
      participants' address local parts; no index answers these, so an
      `english` miss is `english_miss_uncovered`.

    A probe is `present` when its term occurs (case-folded `strpos`) in
    `subject || ' ' || search_text`; it is an `english` hit when the stored
    `search_document` matches `websearch_to_tsquery('english', term)`, a
    `simple` hit when `to_tsvector('simple', ...)` matches the `simple` query,
    and `stopword_empty` when the `english` query has no node. The answer is
    per-class counts plus `material`, which is true when a class's
    `english_miss_uncovered` exceeds `FTS_MATERIAL_SHARE` of its present
    probes. No term, address, subject, identifier value or id is returned.
    """
    if type(limit) is not int or limit < 1 or type(batch_size) is not int or batch_size < 1:
        raise ValueError("a measurement limit and batch size are positive integers")
    messages = communication_messages
    scope: tuple[ColumnElement[bool], ...] = (
        _mine(messages, principal_id),
        messages.c.search_text.is_not(None),
    )
    if ingest_source_id is not None:
        scope += (
            messages.c.text_snapshot_id.in_(_source_snapshots(principal_id, [ingest_source_id])),
        )
    totals = {name: dict.fromkeys(FTS_COUNT_KEYS, 0) for name in FTS_PROBE_CLASSES}
    measured, after = 0, ""
    while measured < limit:
        ids = _measured_ids(connection, scope, after, min(batch_size, limit - measured))
        if not ids:
            break
        measured, after = measured + len(ids), ids[-1]
        for name, counts in _probe_counts(
            connection, principal_id, identifiers_version, ids
        ).items():
            for key, value in counts.items():
                totals[name][key] += value
    deferred = int(
        connection.execute(
            select(func.count()).where(*scope, messages.c.message_id > after)
        ).scalar_one()
    )
    material = any(
        counts["english_miss_uncovered"] > FTS_MATERIAL_SHARE * counts["present"]
        for counts in totals.values()
    )
    return {
        "identifier_version": identifiers_version,
        "messages_measured": measured,
        "messages_deferred": deferred,
        "classes": totals,
        "material_share": FTS_MATERIAL_SHARE,
        "english_miss_uncovered_material": material,
    }
