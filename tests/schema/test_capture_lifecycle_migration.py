def test_the_frozen_ddl_names_every_declared_column_constraint_and_index() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    flat = _WHITESPACE.sub(" ", source)
    for table in (capture_lifecycle_events, capture_lifecycle_receipts):
        assert f"CREATE TABLE knowledge.{table.name} (" in source
        for column in table.c:
            assert re.search(rf"\b{column.name}\b", source), (table.name, column.name)
        for constraint in table.constraints:
            if constraint.name is not None and not str(constraint.name).startswith("_"):
                assert f"CONSTRAINT {constraint.name} " in flat, (table.name, constraint.name)
        for index in table.indexes:
            assert f"INDEX {index.name} ON knowledge.{table.name}" in flat, (table.name, index.name)
    for name in TRIGGERS | FUNCTIONS | JOB_CONSTRAINTS | {ROOT_UNIQUE}:
        assert name in source, name


