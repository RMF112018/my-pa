def test_the_revision_writes_no_rows() -> None:
    tree = ast.parse(MIGRATION.read_text(encoding="utf-8"))
    docstring = ast.get_docstring(tree, clean=False)
    texts = [
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and node.value != docstring
    ]
    flattened = _WHITESPACE.sub(" ", " ".join(texts)).upper()
    for statement in ("INSERT INTO", "UPDATE KNOWLEDGE", "DELETE FROM", "COPY KNOWLEDGE"):
        assert statement not in flattened, statement
    assert not any(
        isinstance(node, ast.Attribute) and node.attr in {"bulk_insert", "insert", "update"}
        for node in ast.walk(tree)
    )


