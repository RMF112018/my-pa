@pytest.mark.database
def test_an_empty_downgrade_unwinds_everything_and_upgrades_again(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), "head")
    with engine.begin() as connection:
        _seed_root(connection)
    command.downgrade(_config(), PREVIOUS)
    assert _version(engine) == PREVIOUS
    assert not _tables(engine) & TABLE_NAMES
    assert not {"lease_generation", "pause_cause"} & _job_columns(engine)
    assert not ({ROOT_UNIQUE} | JOB_CONSTRAINTS) & _constraints(engine)
    with engine.connect() as connection:
        functions = set(
            connection.execute(
                text(
                    "SELECT p.proname FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
    assert not functions & FUNCTIONS
    # The synthetic root, version and jobs survive the round trip.
    assert _scalar(engine, "SELECT count(*) FROM knowledge.capture_jobs") == 2
    command.upgrade(_config(), "head")
    assert _version(engine) == REVISION
