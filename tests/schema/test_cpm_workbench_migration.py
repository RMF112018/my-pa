def _catalog(engine: Engine) -> dict[str, list[str]]:
    """Every constraint, index, trigger and function of the schema, as text."""
    queries = {
        "constraints": (
            "SELECT c.relname || '.' || con.conname || ' ' || pg_get_constraintdef(con.oid) "
            "FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid "
            "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = :schema"
        ),
        "indexes": "SELECT indexdef FROM pg_indexes WHERE schemaname = :schema",
        "triggers": (
            "SELECT c.relname || '.' || t.tgname FROM pg_trigger t JOIN pg_class c "
            "ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = :schema AND NOT t.tgisinternal"
        ),
        "functions": (
            "SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' "
            "FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
            "WHERE n.nspname = :schema"
        ),
        "relations": (
            "SELECT c.relname || ' ' || c.relkind::text FROM pg_class c JOIN pg_namespace n "
            "ON n.oid = c.relnamespace WHERE n.nspname = :schema"
        ),
    }
    with engine.connect() as connection:
        return {
            kind: sorted(connection.execute(text(query), {"schema": SCHEMA}).scalars())
            for kind, query in queries.items()
        }


@pytest.mark.database
def test_clean_downgrade_removes_only_cpm_objects_and_reupgrades(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    at_previous = _catalog(engine)
    command.upgrade(_config(), REVISION)
    at_head = _catalog(engine)
    added = {kind: set(at_head[kind]) - set(at_previous[kind]) for kind in at_head}
    assert not any(set(at_previous[kind]) - set(at_head[kind]) for kind in at_head)
    assert {name.split("(")[0] for name in added["functions"]} == set(CPM_FUNCTIONS)
    assert {
        line.split(" ")[0].split(".")[1]
        for line in added["constraints"]
        if line.split(".")[0] in {"enrollments", "source_object_versions"}
    } == {name for _, name, _ in SUPPORT_UNIQUES}
