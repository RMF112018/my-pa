def _created_constraints() -> dict[str, set[str]]:
    """`CONSTRAINT <name>` per created table, read from the revision's own DDL."""
    module = _module()
    created: dict[str, set[str]] = {}
    for name, ddl, indexes in module["_TABLES"]:  # type: ignore[attr-defined]
        found = set(re.findall(r"CONSTRAINT (\w+)", _flat(str(ddl))))
        found |= {re.search(r"INDEX (\w+)", index).group(1) for index in indexes}  # type: ignore[union-attr]
        created[str(name)] = found
    accepted_name, _ = module["_ACCEPTED_RUN"]  # type: ignore[misc]
    created["schedule_publications"].add(str(accepted_name))
    for table, name, _definition in module["_LIVE_FOREIGN_KEYS"]:  # type: ignore[attr-defined]
        created[str(table)].add(str(name))
    return created


def test_frozen_ddl_names_every_declared_constraint() -> None:
    """The revision's text and `tables.py` name the same objects, table for table.

    Definitions are compared on a server by
    `test_runtime_metadata_matches_the_revision`; this is the static half.
    """
    created = _created_constraints()
    assert set(created) == set(CPM_TABLES)
    for table in DECLARED:
        declared = {str(c.name) for c in table.constraints if c.name}
        declared |= {str(index.name) for index in table.indexes}
        assert declared == created[table.name], (
            table.name,
            sorted(declared ^ created[table.name]),
        )
    # The two support uniques exist only in the database (contract D-04).
    for live, name, _ in SUPPORT_UNIQUES:
        live_table = tables.METADATA.tables[f"{SCHEMA}.{live}"]
        assert name not in {str(c.name) for c in live_table.constraints}, name
        assert name in _code(), name


