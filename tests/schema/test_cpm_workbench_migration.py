def _definitions(engine: Engine, schema: str) -> dict[str, dict[str, list[tuple[str, ...]]]]:
    snapshot: dict[str, dict[str, list[tuple[str, ...]]]] = {}
    with engine.connect() as connection:
        for table in CPM_TABLES:
            snapshot[table] = {
                kind: sorted(
                    tuple(
                        str(value)
                        .replace(f"{schema}.", "<schema>.")
                        .replace(f"{SCHEMA}.", "<schema>.")
                        for value in row
                    )
                    for row in connection.execute(text(query), {"schema": schema, "table": table})
                )
                for kind, query in _CATALOG.items()
            }
    return snapshot


@pytest.mark.database
def test_runtime_metadata_matches_the_revision(disposable_database: str, engine: Engine) -> None:
    """Section 4: the declared tables, built by SQLAlchemy beside the migrated ones, agree.

    Every constraint (`pg_get_constraintdef`), column (type, nullability,
    default, precision) and index (`pg_get_indexdef`) of the seven tables built
    from `tables.py` into a scratch schema equals the revision's, so a CHECK
    text, default or index that drifted in either fails here (R6-F14).
    """
    del disposable_database
    command.upgrade(_config(), "head")
    copies = MetaData()
    for live in (*LIVE_TABLES, "sources", "source_objects"):
        tables.METADATA.tables[f"{SCHEMA}.{live}"].to_metadata(copies)
    built = [
        table.to_metadata(
            copies,
            schema="cpm_parity",
            referred_schema_fn=lambda _t, _s, constraint, referred: (
                "cpm_parity"
                if constraint.elements[0].target_fullname.split(".")[1].startswith("schedule_")
                else referred
            ),
        )
        for table in DECLARED
    ]
    with engine.begin() as connection:
        connection.execute(text("CREATE SCHEMA cpm_parity"))
        copies.create_all(connection, tables=built)
    try:
        migrated = _definitions(engine, SCHEMA)
        declared = _definitions(engine, "cpm_parity")
        for table in CPM_TABLES:
            for kind in _CATALOG:
                assert migrated[table][kind] == declared[table][kind], (table, kind)
            assert migrated[table]["constraints"], table
    finally:
        with engine.begin() as connection:
            connection.execute(text("DROP SCHEMA cpm_parity CASCADE"))


