def _offline(target: str, *, down: bool = False) -> str:
    buffer = io.StringIO()
    action = command.downgrade if down else command.upgrade
    action(_config(buffer), target, sql=True)
    return _flat(buffer.getvalue())


_LIVE_REFERENCE: Final = re.compile(
    r"\bknowledge\.(enrollments|enrollment_objects|source_object_versions|projects)\b"
)


def test_live_table_work_is_last_in_the_upgrade(monkeypatch: pytest.MonkeyPatch) -> None:
    """Section 6 (R6-F02, RR1-F02): nothing names a live table before the last trigger."""
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{PREVIOUS}:{REVISION}")
    body = rendered[rendered.index(f"Running upgrade {PREVIOUS} -> {REVISION}") :]
    assert body.index("SET LOCAL lock_timeout = '10s'") < body.index("CREATE TABLE")
    last_trigger = body.rindex("CREATE CONSTRAINT TRIGGER")
    last_trigger = max(last_trigger, body.rindex("CREATE TRIGGER "))
    first_live = _LIVE_REFERENCE.search(body)
    assert first_live is not None
    assert first_live.start() > last_trigger, first_live.group(0)
    preflight = body.index("cpm workbench preflight")
    assert last_trigger < preflight < body.index("CREATE UNIQUE INDEX an_enrollment_is")
    # Every live-table statement is one of the eight section 6 steps 6-8 name.
    live = [m.group(0) for m in _LIVE_REFERENCE.finditer(body)]
    assert sorted(set(live)) == sorted(f"knowledge.{name}" for name in LIVE_TABLES)
    assert f"SET version_num='{REVISION}'" in body


def test_offline_downgrade_refuses_first(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    assert rendered.index("SET LOCAL lock_timeout = '10s'") < rendered.index(REFUSAL)
    refusal = rendered.index(REFUSAL)
    assert rendered.index("DROP TRIGGER") > refusal
    for table in CPM_TABLES:
        assert rendered.index(f"DROP TABLE knowledge.{table} RESTRICT") > refusal
    # The live-table drops come after every CPM table is gone.
    last_table = max(
        rendered.index(f"DROP TABLE knowledge.{table} RESTRICT") for table in CPM_TABLES
    )
    for live, name, _ in SUPPORT_UNIQUES:
        assert rendered.index(f"ALTER TABLE knowledge.{live} DROP CONSTRAINT {name}") > last_table
    assert f"SET version_num='{PREVIOUS}'" in rendered


