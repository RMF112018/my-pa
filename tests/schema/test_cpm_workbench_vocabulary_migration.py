def _config() -> Config:
    return Config(str(ROOT / "alembic.ini"))


def _source(path: Path = MIGRATION) -> str:
    return path.read_text(encoding="utf-8")


def _code() -> str:
    """The revision without its docstring."""
    return _source().split('"""', 2)[2]


def _namespace(path: Path = MIGRATION) -> dict[str, object]:
    """A revision's namespace (each imports only `alembic` and `typing`)."""
    namespace: dict[str, object] = {}
    exec(compile(_source(path), str(path), "exec"), namespace)  # noqa: S102
    return namespace


def _literals(block: object) -> list[str]:
    return re.findall(r"'([^']+)'", str(block))


