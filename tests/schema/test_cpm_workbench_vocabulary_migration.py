@pytest.mark.database
@pytest.mark.parametrize("case", sorted(_REFUSAL_CASES))
def test_downgrade_refuses_while_schedule_vocabulary_is_used(
    disposable_database: str, engine: Engine, case: str
) -> None:
    """Each clause alone refuses; nothing is deleted and the head stays."""
    del disposable_database
    command.upgrade(_config(), REVISION)
    at_head = _checks(engine)
    _REFUSAL_CASES[case](engine)
    with pytest.raises(DBAPIError) as refused:
        command.downgrade(_config(), PREVIOUS)
    assert getattr(refused.value.orig, "sqlstate", None) == RESTRICT_VIOLATION
    assert REFUSAL in str(refused.value)
    assert _version(engine) == REVISION
    assert _checks(engine) == at_head
    with engine.connect() as connection:
        rows = connection.execute(
            text(
                "SELECT (SELECT count(*) FROM knowledge.audit_events) "
                "+ (SELECT count(*) FROM knowledge.worker_heartbeats)"
            )
        ).scalar_one()
    assert rows == 1


@pytest.mark.database
def test_clean_downgrade_restores_the_before_checks_and_reupgrades(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    before = _checks(engine)
    command.upgrade(_config(), REVISION)
    at_head = _checks(engine)
    assert (
        set(before)
        == set(at_head)
        == {
            "capability_is_known",
            "purpose_is_known",
            "worker_plane_is_known",
        }
    )
    for name in at_head:
        assert before[name] != at_head[name], name
    assert "'schedule'" in at_head["worker_plane_is_known"]
    assert "'schedule_read'" in at_head["purpose_is_known"]
    assert "'schedule_changes.list'" in at_head["capability_is_known"]
    command.downgrade(_config(), PREVIOUS)
    assert _version(engine) == PREVIOUS
    assert _checks(engine) == before
    with pytest.raises(DBAPIError) as refused, engine.begin() as connection:
        _heartbeat(connection, plane="schedule")
    assert getattr(refused.value.orig, "sqlstate", None) == CHECK_VIOLATION
    command.upgrade(_config(), REVISION)
    assert _checks(engine) == at_head


def _run_revision(connection_engine: Engine, step: str) -> str:
    """Run this revision's `upgrade`/`downgrade` on one connection; return its `lock_timeout`."""
    namespace = _namespace()
    with connection_engine.connect() as connection:
        with connection.begin(), Operations.context(MigrationContext.configure(connection)):
            namespace[step]()  # type: ignore[operator]
        return str(connection.execute(text("SHOW lock_timeout")).scalar_one())


@pytest.mark.database
def test_lock_timeout_is_transaction_local(disposable_database: str, engine: Engine) -> None:
    """`SET LOCAL`: the 10 s timeout ends with the revision's own transaction."""
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    before = _checks(engine)
    with engine.connect() as connection:
        default = str(connection.execute(text("SHOW lock_timeout")).scalar_one())
    assert default != "10s"
    assert _run_revision(engine, "upgrade") == default
    assert "'schedule'" in _checks(engine)["worker_plane_is_known"]
    assert _run_revision(engine, "downgrade") == default
    assert _checks(engine) == before


