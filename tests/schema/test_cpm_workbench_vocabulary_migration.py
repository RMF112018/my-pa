"""The one CPM Workbench S5b-2 revision, `621ef6786c64` (worker contract section 3.14).

Generated by `alembic revision` against the sole head `6c2306330ceb`. This
module proves:

* **the graph** -- exactly one head, this revision, directly on the S5b-1
  revision `6c2306330ceb`, and 125 revision files;
* **the freeze** -- the revision imports nothing from the package it migrates,
  writes no row and grants nothing; its BEFORE texts are byte copies of what
  `023f8f7eb499` (capabilities), `c5260943d933` (purposes) and `b727e870d45e`
  (planes) left; its AT sets are sorted literals equal to the live enums (251 =
  240 + 11 native, and 62) and to the `tables.py` heartbeat declaration;
* on disposable databases: empty to head admits every Schedule name and the
  `schedule` plane; the downgrade refuses while any audit event names a
  Schedule capability or purpose or any heartbeat names the plane, one clause at
  a time; a clean downgrade restores the BEFORE checks and upgrades again; and
  the `lock_timeout` is transaction-local.

The file name routes the database tests here to the migration tiers
(`tests/db/fixtures.py`): the empty-to-head test carries its own marker and the
others default to `migration_edge`. Tests with no `database` marker run in
FAST. Every value is synthetic.
"""

