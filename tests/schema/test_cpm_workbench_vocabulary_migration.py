def test_the_revision_imports_no_package_module() -> None:
    imported: set[str] = set()
    for node in ast.walk(ast.parse(_source())):
        if isinstance(node, ast.ImportFrom) and node.module is not None:
            imported.add(node.module)
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert imported <= {"alembic", "__future__", "typing"}
    assert "my_pa" not in _source()


def test_the_revision_writes_no_row_and_grants_nothing() -> None:
    """Section 3.14: no table, column, index, trigger, function, row or grant."""
    code = "\n".join(
        line for line in _code().splitlines() if not line.lstrip().startswith("#")
    ).upper()
    for statement in ("INSERT INTO", "UPDATE KNOWLEDGE", "DELETE FROM", "COPY ", "TRUNCATE"):
        assert statement not in code, statement
    for statement in ("CREATE TABLE", "ADD COLUMN", "CREATE INDEX", "CREATE TRIGGER"):
        assert statement not in code, statement
    assert "CREATE FUNCTION" not in code and "CREATE OR REPLACE" not in code
    assert "GRANT " not in code
    assert "REVOKE " not in code
    assert "MCP_OBJECT_GRANTS" not in code
    assert "OWNER TO" not in code and "SET ROLE" not in code
    assert "ALTER DEFAULT PRIVILEGES" not in code


def test_before_texts_are_byte_copies() -> None:
    """Each BEFORE text is exactly what its predecessor revision left."""
    mine = _namespace()
