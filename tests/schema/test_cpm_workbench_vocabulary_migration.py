def _version(engine: Engine) -> str:
    with engine.connect() as connection:
        return str(connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one())


def _checks(engine: Engine) -> dict[str, str]:
    with engine.connect() as connection:
        rows = connection.execute(
            text(
                "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                "JOIN pg_class rel ON rel.oid = con.conrelid "
                "JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace "
                "WHERE nsp.nspname = :schema AND con.conname IN "
                "('capability_is_known', 'purpose_is_known', 'worker_plane_is_known')"
            ),
            {"schema": SCHEMA},
        ).all()
    return {str(name): str(definition) for name, definition in rows}


def _audit(connection: Connection, *, capability: str, purpose: str, suffix: str) -> None:
    connection.execute(
        insert(audit_events).values(
            audit_id=f"audit_{suffix}",
            correlation_id=f"corr_{suffix}",
            principal_id=P,
            capability=capability,
            purpose=purpose,
            outcome="allowed",
            policy_version="policy-v1",
            scope_source_id_count=0,
            recorded_at=WHEN,
        )
    )


def _heartbeat(connection: Connection, *, plane: str) -> None:
    connection.execute(
        insert(worker_heartbeats).values(worker_owner="cpmvocab01", principal_id=P, plane=plane)
    )


@pytest.mark.database
@pytest.mark.migration_empty_to_head
def test_empty_to_head_admits_every_schedule_name_and_plane(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), "head")
    assert _version(engine) == HEAD
    with engine.begin() as connection:
        for index, capability in enumerate(sorted(S5B2_CAPABILITIES)):
            _audit(
                connection,
                capability=capability,
                purpose="schedule_read",
                suffix=f"cpmvocab{index:04d}a",
            )
        _audit(
            connection,
            capability="schedule_publications.import",
            purpose="schedule_import",
            suffix="cpmvocab0100a",
        )
        _heartbeat(connection, plane="schedule")
    with engine.connect() as connection:
        audited = connection.execute(
            text("SELECT count(*) FROM knowledge.audit_events WHERE capability = ANY(:names)"),
            {"names": sorted(S5B2_CAPABILITIES)},
        ).scalar_one()
        beats = connection.execute(
            text("SELECT count(*) FROM knowledge.worker_heartbeats WHERE plane = 'schedule'")
        ).scalar_one()
    assert (audited, beats) == (8, 1)
    # An unknown plane is still refused: the CHECK was widened, not dropped.
    with pytest.raises(DBAPIError) as refused, engine.begin() as connection:
        _heartbeat(connection, plane="scheduler")
    assert getattr(refused.value.orig, "sqlstate", None) == CHECK_VIOLATION


