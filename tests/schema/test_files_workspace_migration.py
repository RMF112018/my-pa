def _definitions(engine: Engine, schema: str) -> dict[str, dict[str, list[tuple[str, ...]]]]:
    snapshot: dict[str, dict[str, list[tuple[str, ...]]]] = {}
    with engine.connect() as connection:
        for table in PLANE_TABLES:
            snapshot[table] = {
                kind: sorted(
                    tuple(str(value).replace(f"{schema}.", "<schema>.") for value in row)
                    for row in connection.execute(text(query), {"schema": schema, "table": table})
                )
                for kind, query in _CATALOG.items()
            }
    return snapshot


