def _catalog(engine: Engine) -> dict[str, set[str]]:
    with engine.connect() as connection:
        tables = set(
            connection.execute(
                text("SELECT tablename FROM pg_tables WHERE schemaname = :schema"),
                {"schema": SCHEMA},
            ).scalars()
        )
        constraints = set(
            connection.execute(
                text(
                    "SELECT c.conname FROM pg_constraint c "
                    "JOIN pg_namespace n ON n.oid = c.connamespace WHERE n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
        triggers = set(
            connection.execute(
                text(
                    "SELECT t.tgname FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace "
                    "WHERE NOT t.tgisinternal AND n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
        functions = set(
            connection.execute(
                text(
                    "SELECT p.proname FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
        version = set(connection.execute(text("SELECT version_num FROM alembic_version")).scalars())
    return {
        "tables": tables,
        "constraints": constraints,
        "triggers": triggers,
        "functions": functions,
        "version": version,
    }


def _assert_meeting_schema_present(engine: Engine, *, at: str = HEAD) -> None:
    catalog = _catalog(engine)
    assert catalog["version"] == {at}
    assert catalog["tables"] >= MEETING_TABLE_NAMES
    assert OWNER_UNIQUE in catalog["constraints"]
    assert catalog["triggers"] >= set(TRIGGERS)
    assert catalog["functions"] >= set(TRIGGERS.values())


def _assert_meeting_schema_absent(engine: Engine) -> None:
    catalog = _catalog(engine)
    assert catalog["version"] == {PREVIOUS}
    assert not catalog["tables"] & MEETING_TABLE_NAMES
    assert OWNER_UNIQUE not in catalog["constraints"]
    assert not catalog["triggers"] & set(TRIGGERS)
    assert not catalog["functions"] & set(TRIGGERS.values())


