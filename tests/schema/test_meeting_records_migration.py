def test_revision_imports_no_domain_or_persistence_modules() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    imported: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and node.module is not None:
            imported.add(node.module)
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert imported <= {"alembic", "__future__", "typing"}
    assert "my_pa" not in source
    assert "create_all" not in source


def test_the_frozen_ddl_names_every_declared_table_constraint_and_index() -> None:
    """The revision's text and `tables.py` name the same Meeting schema objects.

    Parity of the *definitions* is proved on a server by the WP-MTG-02
    persistence tests and by `test_every_revision_denotes_one_schema.py`; this is
    the static half, which runs without one.
    """
    source = MIGRATION.read_text(encoding="utf-8")
    for table in MEETING_TABLES:
        assert f"CREATE TABLE knowledge.{table.name} (" in source
        for column in table.c:
            assert re.search(rf"\b{column.name}\b", source), (table.name, column.name)
        for constraint in table.constraints:
            if constraint.name is not None and not str(constraint.name).startswith("_"):
                assert str(constraint.name) in source, (table.name, constraint.name)
        for index in table.indexes:
            assert f"INDEX {index.name} ON knowledge.{table.name}" in _WHITESPACE.sub(
                " ", source
            ), (table.name, index.name)
    assert OWNER_UNIQUE in source
    for trigger, function in TRIGGERS.items():
        assert trigger in source
        assert function in source


