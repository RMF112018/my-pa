@pytest.mark.database
def test_a_write_request_completes_exactly_once(disposable_database: str, engine: Engine) -> None:
    del disposable_database
    command.upgrade(_config(), "head")
    with engine.begin() as connection:
        ids = _seed_meeting(connection)
        _reserve(connection, "mig-complete")
        _reserve(connection, "mig-identity")

    def complete(connection: Connection, key: str) -> None:
        connection.execute(
            update(meeting_write_requests)
            .where(meeting_write_requests.c.idempotency_key == key)
            .values(
                completed_at=WHEN,
                meeting_id=ids["meeting"],
                meeting_series_id=ids["series"],
                meeting_history_id=ids["history"],
                result_version=1,
            )
        )

    with engine.begin() as connection:
        complete(connection, "mig-complete")
    # A second completion, a change of identity, an update that does not
    # complete, and a delete are each refused by the transition trigger.
    _refused_by_trigger(engine, lambda c: complete(c, "mig-complete"))
    _refused_by_trigger(
        engine,
        lambda c: c.execute(
            update(meeting_write_requests)
            .where(meeting_write_requests.c.idempotency_key == "mig-identity")
            .values(request_digest="d" * 64)
        ),
    )
    _refused_by_trigger(
        engine,
        lambda c: c.execute(
            update(meeting_write_requests)
            .where(meeting_write_requests.c.idempotency_key == "mig-identity")
            .values(created_at=WHEN.replace(hour=13))
        ),
    )
    _refused_by_trigger(
        engine,
        lambda c: c.execute(
            meeting_write_requests.delete().where(
                meeting_write_requests.c.idempotency_key == "mig-identity"
            )
        ),
    )
    _refused_by_trigger(
        engine,
        lambda c: c.execute(
            meeting_write_requests.delete().where(
                meeting_write_requests.c.idempotency_key == "mig-complete"
            )
        ),
    )


