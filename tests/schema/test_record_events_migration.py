@pytest.mark.database
def test_an_empty_downgrade_restores_the_meeting_head_vocabulary_and_drops_everything(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), "head")
    command.downgrade(_config(), PREVIOUS)
    assert _version(engine) == PREVIOUS
    assert not _tables(engine) & TABLE_NAMES
    previous = VOCABULARY_MIGRATION.read_text(encoding="utf-8")
    assert _admitted(engine, "capability_is_known") == frozenset(
        _literals(_constant(previous, "_CAPABILITIES_AT_THIS_REVISION"))
    )
    assert _admitted(engine, "purpose_is_known") == frozenset(
        _literals(_constant(previous, "_PURPOSES_AT_THIS_REVISION"))
    )
    with engine.connect() as connection:
        functions = set(
            connection.execute(
                text(
                    "SELECT p.proname FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
    assert FUNCTION not in functions
    command.upgrade(_config(), REVISION)
    assert _version(engine) == REVISION
