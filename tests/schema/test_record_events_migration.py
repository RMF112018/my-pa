def test_the_at_texts_add_exactly_the_record_event_vocabulary_and_stay_sorted() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    before = _literals(_constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION"))
    at = _literals(_constant(source, "_CAPABILITIES_AT_THIS_REVISION"))
    assert set(at) == set(before) | ADMITTED_CAPABILITIES
    assert len(at) == len(before) + 1 == 190
    assert at == sorted(at)
    purposes_before = _literals(_constant(source, "_PURPOSES_BEFORE_THIS_REVISION"))
    purposes_at = _literals(_constant(source, "_PURPOSES_AT_THIS_REVISION"))
    assert set(purposes_at) == set(purposes_before) | ADMITTED_PURPOSES
    assert len(purposes_at) == len(purposes_before) + 1 == 48
    assert purposes_at == sorted(purposes_at)


def test_head_admits_every_declared_capability_and_purpose() -> None:
    """A subset, not equality: the audit set also holds the operator names.

    The chain head is `0641c354ca85`, which restates the vocabulary in place.
    This revision's own AT set is proven above and no longer is that head.
    """
    source = HEAD_MIGRATION.read_text(encoding="utf-8")
    at = set(_literals(_constant(source, "_CAPABILITIES_AT_THIS_REVISION")))
    purposes_at = set(_literals(_constant(source, "_PURPOSES_AT_THIS_REVISION")))
    declared = {capability.value for capability in Capability}
    assert declared <= at
    assert {purpose.value for purpose in Purpose} <= purposes_at
    assert at - declared == {capability.value for capability in NativeSourceCapability}


