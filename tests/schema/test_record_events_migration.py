# ---- no backfill (RE-AC-083) --------------------------------------------------------


def test_the_revision_writes_no_rows() -> None:
    """Every SQL text the revision can execute: no INSERT, UPDATE, DELETE or COPY.

    Read from the string constants (comments and the docstring excluded), so
    the phrase "byte copy" in a comment is not mistaken for a statement.
    """
    tree = ast.parse(MIGRATION.read_text(encoding="utf-8"))
    docstring = ast.get_docstring(tree, clean=False)
    texts = [
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and node.value != docstring
    ]
    flattened = _WHITESPACE.sub(" ", " ".join(texts)).upper()
    for statement in ("INSERT INTO", "UPDATE KNOWLEDGE", "DELETE FROM", "COPY KNOWLEDGE"):
        assert statement not in flattened, statement
    assert not any(
        isinstance(node, ast.Attribute) and node.attr in {"bulk_insert", "insert", "update"}
        for node in ast.walk(tree)
    )


# ---- offline SQL -------------------------------------------------------------------


def test_the_offline_upgrade_emits_the_tables_trigger_and_vocabulary(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{PREVIOUS}:{REVISION}")
    for name in TABLE_NAMES:
        assert f"CREATE TABLE knowledge.{name} (" in rendered
    assert f"CREATE FUNCTION knowledge.{FUNCTION}()" in rendered
    assert f"CREATE TRIGGER {TRIGGER}" in rendered
    assert "ADD CONSTRAINT capability_is_known CHECK" in rendered
    assert "'project_controls.status', 'record_events.list', 'relationship_memory" in rendered
    assert "'meeting_read', 'record_event_read', 'relationship_memory" in rendered
    assert f"SET version_num='{REVISION}'" in rendered


def test_the_offline_downgrade_refuses_first_and_unwinds_everything(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    refusal = rendered.index("refusing to downgrade")
    for name in TABLE_NAMES:
        assert rendered.index(f"DROP TABLE knowledge.{name} RESTRICT") > refusal
    assert f"DROP TRIGGER {TRIGGER}" in rendered
    assert f"DROP FUNCTION knowledge.{FUNCTION}()" in rendered
    restated = rendered.split("ADD CONSTRAINT capability_is_known CHECK")[1]
    assert "'record_events.list'" not in restated.split("ADD CONSTRAINT")[0]
    assert f"SET version_num='{PREVIOUS}'" in rendered


