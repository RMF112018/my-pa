@pytest.mark.database
@pytest.mark.migration
def test_capture_versions_gain_only_the_digest_unique(
    disposable_database: str, engine: Engine, monkeypatch: pytest.MonkeyPatch
) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)

    def facts() -> set[str]:
        with engine.connect() as connection:
            return set(
                connection.execute(
                    text(
                        "SELECT 'constraint ' || con.conname || ' = ' || "
                        "pg_get_constraintdef(con.oid) FROM pg_constraint con "
                        "WHERE con.conrelid = 'knowledge.capture_versions'::regclass "
                        "UNION ALL SELECT 'index ' || pg_get_indexdef(i.indexrelid) "
                        "FROM pg_index i WHERE i.indrelid = 'knowledge.capture_versions'::regclass "
                        "UNION ALL SELECT 'column ' || a.attname || ' ' || "
                        "format_type(a.atttypid, a.atttypmod) || ' ' || a.attnotnull "
                        "FROM pg_attribute a WHERE a.attrelid = "
                        "'knowledge.capture_versions'::regclass AND a.attnum > 0 "
                        "AND NOT a.attisdropped "
                        "UNION ALL SELECT 'trigger ' || t.tgname FROM pg_trigger t "
                        "WHERE t.tgrelid = 'knowledge.capture_versions'::regclass "
                        "AND NOT t.tgisinternal"
                    )
                ).scalars()
            )

    before = facts()
    command.upgrade(_config(), REVISION)
    after = facts()
    added = after - before
    assert not before - after
    assert {fact.split(" = ")[0] for fact in added if fact.startswith("constraint ")} == {
        f"constraint {DATABASE_ONLY_UNIQUE}"
    }
    assert f"constraint {DATABASE_ONLY_UNIQUE} = UNIQUE (version_id, capture_id, " in "".join(added)
    # Only the unique's own backing index accompanies it.
    assert {fact for fact in added if not fact.startswith("constraint ")} == {
        f"index CREATE UNIQUE INDEX {DATABASE_ONLY_UNIQUE} ON knowledge.capture_versions "
        "USING btree (version_id, capture_id, owner_principal_id, content_sha256)"
    }
    # F20: the declaration does not carry it, so the historical revision that
    # builds this table from the declaration emits what it emitted before S1.
    assert DATABASE_ONLY_UNIQUE not in {str(c.name) for c in capture_versions.constraints}
    emitted = _capture_revision_emission(monkeypatch)
    assert DATABASE_ONLY_UNIQUE not in emitted
    lines = sorted(
        line.strip().rstrip(",").strip() for line in emitted.splitlines() if line.strip()
    )
    assert (
        hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()
        == CAPTURE_REVISION_EMISSION_SHA256
    )


