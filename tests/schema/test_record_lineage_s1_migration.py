    assert rendered.index(f"DROP CONSTRAINT {DATABASE_ONLY_UNIQUE}") > refusal
    assert "'issues.create'" not in rendered.split("ADD CONSTRAINT capability_is_known CHECK")[1]
    assert f"SET version_num='{PREVIOUS}'" in rendered


