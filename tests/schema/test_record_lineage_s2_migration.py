def test_the_revision_imports_no_domain_module() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    imported: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and node.module is not None:
            imported.add(node.module)
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert imported <= {"alembic", "__future__", "typing"}
    assert "my_pa" not in source
    assert "create_all" not in source
    code = source.split('"""', 2)[2].upper()
    for statement in ("DELETE FROM", "UPDATE KNOWLEDGE", "GRANT ", "INSERT INTO"):
        assert statement not in code


def test_frozen_ddl_names_every_declared_constraint() -> None:
    """The revision's text and `tables.py` name the same S2 schema objects.

    Parity of the definitions is proved on a server by
    `tests/database/test_lineage_s2_integrity_guards.py`; this is the static half.
    """
    source = MIGRATION.read_text(encoding="utf-8")
    s1 = S1_MIGRATION.read_text(encoding="utf-8")
    # A name the S3 revision adds to one of these tables is in that revision's
    # text instead (the later revision owns it).
    later = S3_MIGRATION.read_text(encoding="utf-8")
    flat = _flat(source)
    flat_later = _flat(later)
    for table in NEW_TABLES:
        assert f"CREATE TABLE knowledge.{table.name} (" in source
        for column in table.c:
            assert re.search(rf"\b{column.name}\b", source) or re.search(
                rf"ADD COLUMN {column.name}\b", later
            ), (table.name, column.name)
        for constraint in table.constraints:
            if constraint.name is not None and not str(constraint.name).startswith("_"):
                assert str(constraint.name) in source or str(constraint.name) in later, (
                    table.name,
                    constraint.name,
                )
        for index in table.indexes:
            assert (
                f"INDEX {index.name} ON knowledge.{table.name}" in flat
                or f"INDEX {index.name} ON knowledge.{table.name}" in flat_later
            ), index.name
    for table in ALTERED_TABLES:
        for column in ADDED_COLUMNS.get(table.name, frozenset()):
            assert column in table.c, (table.name, column)
            assert f"ALTER TABLE knowledge.{table.name} ADD COLUMN {column} " in source
        declared = {str(c.name) for c in table.constraints if c.name}
        # Every name the S1 revision does not create is this revision's, or
        # the S3 revision's.
        for name in declared:
            if name not in s1:
                assert name in source or name in later, (table.name, name)
        for name in WIDENED.get(table.name, frozenset()):
            assert name in declared and name in s1 and name in source, (table.name, name)
    for function in FUNCTIONS | set(REPLACED_FUNCTIONS):
        assert f"knowledge.{function}(" in flat, function
    for table_name, trigger in TRIGGERS:
        assert trigger in source, (table_name, trigger)


def test_before_texts_are_byte_copies_of_the_s1_texts() -> None:
    """Copied, not reconstructed: the S1 texts `downgrade` restores are `264310e0416a`'s."""
    source = MIGRATION.read_text(encoding="utf-8")
    s1 = S1_MIGRATION.read_text(encoding="utf-8")
    assert _constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION") == _constant(
        s1, "_CAPABILITIES_AT_THIS_REVISION"
    )
    assert _constant(source, "_PURPOSES_BEFORE_THIS_REVISION") == _constant(
        s1, "_PURPOSES_AT_THIS_REVISION"
    )
    module = _module()
    widened = module["_WIDENED_CHECKS"]
    assert isinstance(widened, tuple)
    assert {(table, name) for table, name, _, _ in widened} == {
        (table, name) for table, names in WIDENED.items() for name in names
    }
    flat_s1 = _flat(s1)
    for _table, name, before, after in widened:
        # The S1 revision wraps its CHECKs inside `CREATE TABLE`; whitespace aside,
        # the restored text is the one it created.
        assert f"CONSTRAINT {name} CHECK ({before})" in flat_s1, name
        assert before != after
    replaced = module["_REPLACED_FUNCTIONS"]
    assert isinstance(replaced, tuple)
    assert tuple(name for name, _, _ in replaced) == REPLACED_FUNCTIONS
    for name, current, previous in replaced:
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in current
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in previous
        body = previous.split("$$", 1)[1].rsplit("$$", 1)[0]
        # The body between the dollar quotes is byte-identical to the S1 one.
        assert f"$${body}$$" in s1, name
        assert current.split("$$", 1)[1] != previous.split("$$", 1)[1]
    # No revision sits between the S1 revision and this one.
    script = ScriptDirectory.from_config(_config())
    assert script.get_revision(REVISION).down_revision == PREVIOUS


def test_at_vocabulary_adds_exactly_the_s2_names() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    before = _literals(_constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION"))
    at = _literals(_constant(source, "_CAPABILITIES_AT_THIS_REVISION"))
    assert set(at) == set(before) | S2_CAPABILITIES
    assert len(at) == len(before) + len(S2_CAPABILITIES) == 225
    assert at == sorted(at)
    purposes_before = _literals(_constant(source, "_PURPOSES_BEFORE_THIS_REVISION"))
    purposes_at = _literals(_constant(source, "_PURPOSES_AT_THIS_REVISION"))
    assert set(purposes_at) == set(purposes_before) | S2_PURPOSES
    assert len(purposes_at) == len(purposes_before) + len(S2_PURPOSES) == 58
    assert purposes_at == sorted(purposes_at)
    # The head admits every declared name, and the S2 schema-ahead gap is
    # exactly the S2 names the domain does not declare yet (none).
    # The S3 names, declared since, are the S3 revision's (6f1476b8da52).
    declared = {capability.value for capability in Capability} - S3_CAPABILITIES - S4_CAPABILITIES
    native = {capability.value for capability in NativeSourceCapability}
    assert set(at) == declared | native | gap.lineage_s2_admitted_ahead("capability")
    purposes = {purpose.value for purpose in Purpose} - S3_PURPOSES - S4_PURPOSES
    assert set(purposes_at) == purposes | gap.lineage_s2_admitted_ahead("purpose")
    assert S2_CAPABILITIES & declared == gap.S2_CAPABILITIES_DECLARED_BY_DOMAIN
    assert S2_PURPOSES & purposes == gap.S2_PURPOSES_DECLARED_BY_DOMAIN
    assert gap.LINEAGE_S2_DECLARED_BY_DOMAIN is (
        declared >= S2_CAPABILITIES and purposes >= S2_PURPOSES
    )
    assert gap.lineage_s2_admitted_ahead("capability") == frozenset()
    assert gap.lineage_s2_admitted_ahead("purpose") == frozenset()
    assert len(S2_CAPABILITIES) == 8
    assert len(S2_PURPOSES) == 1


# ---- offline SQL -------------------------------------------------------------


def _offline(target: str, *, down: bool = False) -> str:
    buffer = io.StringIO()
    action = command.downgrade if down else command.upgrade
    action(_config(buffer), target, sql=True)
    return _flat(buffer.getvalue())


def test_offline_downgrade_refuses_first(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    refusal = rendered.index("refusing to downgrade d020b532ad7d")
    for name in NEW_TABLE_NAMES:
        assert rendered.index(f"DROP TABLE knowledge.{name} RESTRICT") > refusal
    for table, trigger in TRIGGERS:
        assert rendered.index(f"DROP TRIGGER {trigger} ON knowledge.{table}") > refusal
    for function in FUNCTIONS:
        assert rendered.index(f"DROP FUNCTION knowledge.{function}()") > refusal
    for table, columns in ADDED_COLUMNS.items():
        for column in columns:
            assert rendered.index(f"ALTER TABLE knowledge.{table} DROP COLUMN {column}") > refusal
    assert "'issues.close'" not in rendered.split("ADD CONSTRAINT capability_is_known CHECK")[1]
    assert f"SET version_num='{PREVIOUS}'" in rendered
    upgraded = _offline(f"{PREVIOUS}:{REVISION}")
    assert "'issues.close', 'issues.closure_readiness'" in upgraded
    assert f"SET version_num='{REVISION}'" in upgraded


