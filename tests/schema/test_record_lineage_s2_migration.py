def _s1_texts(engine: Engine) -> dict[str, object]:
    """Every S1 text the revision touches: the widened CHECKs, the two bodies, the columns."""
    names = sorted(name for names in WIDENED.values() for name in names)
    with engine.connect() as connection:
        checks = dict(
            connection.execute(
                text(
                    "SELECT c.relname || '.' || con.conname, pg_get_constraintdef(con.oid) "
                    "FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace "
                    "WHERE n.nspname = :schema AND con.conname = ANY(:names)"
                ),
                {"schema": SCHEMA, "names": names},
            ).all()
        )
        audit = dict(
            connection.execute(
                text(
                    "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                    "WHERE con.conrelid = 'knowledge.audit_events'::regclass "
                    "AND con.conname IN ('capability_is_known', 'purpose_is_known')"
                )
            ).all()
        )
        functions = dict(
            connection.execute(
                text(
                    "SELECT p.proname, pg_get_functiondef(p.oid) FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace "
                    "WHERE n.nspname = :schema AND p.proname = ANY(:names)"
                ),
                {"schema": SCHEMA, "names": list(REPLACED_FUNCTIONS)},
            ).all()
        )
        columns = sorted(
            connection.execute(
                text(
                    "SELECT table_name || '.' || column_name || ' ' || data_type || ' ' || "
                    "is_nullable || ' ' || coalesce(column_default, '') "
                    "FROM information_schema.columns WHERE table_schema = :schema "
                    "AND table_name IN ('issue_revisions', 'record_links', "
                    "'record_link_revisions', 'lineage_write_requests')"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
        constraint_names = sorted(
            connection.execute(
                text(
                    "SELECT c.relname || '.' || con.conname FROM pg_constraint con "
                    "JOIN pg_class c ON c.oid = con.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = :schema "
                    "AND c.relname IN ('issue_revisions', 'record_links', "
                    "'record_link_revisions', 'lineage_write_requests')"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )
    assert len(checks) == len(names) and len(functions) == 2
    return {
        "checks": checks,
        "audit": audit,
        "functions": functions,
        "columns": columns,
        "constraints": constraint_names,
    }


@pytest.mark.database
@pytest.mark.migration
def test_downgrade_restores_every_s1_text(disposable_database: str, engine: Engine) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    at_s1 = _s1_texts(engine)
    command.upgrade(_config(), REVISION)
    at_s2 = _s1_texts(engine)
    assert at_s2["checks"] != at_s1["checks"]
    assert at_s2["functions"] != at_s1["functions"]
    command.downgrade(_config(), PREVIOUS)
    _assert_absent(engine)
    assert _s1_texts(engine) == at_s1
    # Back to this revision: the S3 revision widens some of these texts again.
    command.upgrade(_config(), REVISION)
    _assert_present(engine, at=REVISION)
    assert _s1_texts(engine) == at_s2


