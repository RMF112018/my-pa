def test_frozen_ddl_names_every_declared_constraint() -> None:
    """The revision's text and `tables.py` name the same S3.1 schema objects.

    Parity of the definitions is proved on a server by
    `tests/database/test_lineage_s31_integrity_guards.py`; this is the static half.
    """
    source = MIGRATION.read_text(encoding="utf-8")
    flat = _joined(source)
    earlier = _flat("".join(path.read_text(encoding="utf-8") for path in EARLIER))
    for table in ALTERED_TABLES:
        for column in ADDED_COLUMNS.get(table.name, frozenset()):
            assert column in table.c, (table.name, column)
            assert f"ALTER TABLE knowledge.{table.name} ADD COLUMN {column} " in flat, column
        declared = {str(c.name) for c in table.constraints if c.name}
        for name in WIDENED.get(table.name, frozenset()):
            assert name in declared and name in earlier and name in source, (table.name, name)
        for name in ADDED.get(table.name, frozenset()):
            assert name in declared and name in source, (table.name, name)
            assert f"CONSTRAINT {name} CHECK" not in earlier, (table.name, name)
        if table.name in DROPPED_FROM:
            assert DROPPED not in declared, table.name
        # Every constraint the earlier revisions do not create is this revision's.
        for name in declared:
            if f" {name} " not in earlier and f'"{name}"' not in earlier:
                assert name in source, (table.name, name)
    assert {index.name for index in lineage_write_requests.indexes} >= {INDEX}
    assert (
        f"CREATE INDEX {INDEX} ON knowledge.lineage_write_requests (principal_id, "
        "decision_channel, asserting_client_id, created_at)" in flat
    )
    for function in REPLACED_FUNCTIONS:
        assert f"CREATE OR REPLACE FUNCTION knowledge.{function}()" in source, function
    # `lineage_backfill_runs` keeps its attested CHECK (section 5.1).
    code = source.split('"""', 2)[2]
    assert '"lineage_backfill_runs"' not in code
    assert "knowledge.lineage_backfill_runs" not in code


def test_before_texts_are_byte_copies_of_the_s4_texts() -> None:
    """Copied, not reconstructed: the texts `downgrade` restores are what S4 left."""
    source = MIGRATION.read_text(encoding="utf-8")
    s4 = EARLIER[-1].read_text(encoding="utf-8")
    assert _constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION") == _constant(
        s4, "_CAPABILITIES_AT_THIS_REVISION"
    )
    # The purpose vocabulary is not restated (section 5.3: no new purpose).
    assert "purpose_is_known" not in source.split('"""', 2)[2]
    module = _module()
    widened = module["_WIDENED_CHECKS"]
    assert isinstance(widened, tuple)
    assert {(table, name) for table, name, _, _ in widened} == {
        (table, name) for table, names in WIDENED.items() for name in names
    }
    for table, name, before, after in widened:
        assert before == _left_text(table, name), (table, name)
        assert before != after
    dropped = module["_DROPPED_CHECKS"]
    assert isinstance(dropped, tuple)
    assert {(table, name) for table, name, _ in dropped} == {
        (table, DROPPED) for table in DROPPED_FROM
    }
    for table, name, before in dropped:
        assert before == _left_text(table, name), table
    added = module["_ADDED_CHECKS"]
    assert isinstance(added, tuple)
    assert {(table, name) for table, name, _ in added} == {
        (table, name) for table, names in ADDED.items() for name in names
    }
    replaced = module["_REPLACED_FUNCTIONS"]
    assert isinstance(replaced, tuple)
    assert tuple(name for name, _, _ in replaced) == REPLACED_FUNCTIONS
    for name, current, previous in replaced:
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in current
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in previous
        body = previous.split("$$", 1)[1].rsplit("$$", 1)[0]
        assert body == _left_function_body(name), name
        assert current.split("$$", 1)[1] != previous.split("$$", 1)[1]
    script = ScriptDirectory.from_config(_config())
    assert script.get_revision(REVISION).down_revision == PREVIOUS


