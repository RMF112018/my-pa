def _s4_texts(engine: Engine) -> dict[str, object]:
    """Every S4 text the revision touches: CHECKs, bodies, columns, indexes, audit."""
    tables = [table.name for table in ALTERED_TABLES]
    with engine.connect() as connection:
        checks = sorted(
            connection.execute(
                text(
                    "SELECT c.relname || '.' || con.conname || ' ' || "
                    "pg_get_constraintdef(con.oid) "
                    "FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace "
                    "WHERE n.nspname = :schema AND c.relname = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": tables},
            ).scalars()
        )
        audit = dict(
            connection.execute(
                text(
                    "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                    "WHERE con.conrelid = 'knowledge.audit_events'::regclass "
                    "AND con.conname IN ('capability_is_known', 'purpose_is_known')"
                )
            ).all()
        )
        functions = dict(
            connection.execute(
                text(
                    "SELECT p.proname, pg_get_functiondef(p.oid) FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace "
                    "WHERE n.nspname = :schema AND p.proname = ANY(:names)"
                ),
                {"schema": SCHEMA, "names": list(REPLACED_FUNCTIONS)},
            ).all()
        )
        columns = sorted(
            connection.execute(
                text(
                    "SELECT table_name || '.' || column_name || ' ' || data_type || ' ' || "
                    "is_nullable || ' ' || coalesce(column_default, '') "
                    "FROM information_schema.columns WHERE table_schema = :schema "
                    "AND table_name = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": tables},
            ).scalars()
        )
        indexes = sorted(
            connection.execute(
                text(
                    "SELECT tablename || '.' || indexname || ' ' || indexdef FROM pg_indexes "
                    "WHERE schemaname = :schema AND tablename = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": tables},
            ).scalars()
        )
    assert len(functions) == len(REPLACED_FUNCTIONS)
    return {
        "checks": checks,
        "audit": audit,
        "functions": functions,
        "columns": columns,
        "indexes": indexes,
    }


@pytest.mark.database
@pytest.mark.migration
def test_downgrade_restores_every_s4_text(disposable_database: str, engine: Engine) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    at_s4 = _s4_texts(engine)
    command.upgrade(_config(), REVISION)
    at_s31 = _s4_texts(engine)
    for key in ("checks", "audit", "functions", "columns", "indexes"):
        assert at_s31[key] != at_s4[key], key
    command.downgrade(_config(), PREVIOUS)
    _assert_absent(engine)
    assert _s4_texts(engine) == at_s4
    command.upgrade(_config(), REVISION)
    _assert_present(engine)
    assert _s4_texts(engine) == at_s31


