def _constant(source: str, name: str) -> str:
    """One spelled `Final` literal, as written, including its line breaks."""
    found = re.search(rf"^{name}: Final = \(\n(.*?)^\)\n", source, re.S | re.M)
    assert found is not None, f"{name} is not spelled in the revision"
    return found.group(1)


def _literals(block: str) -> list[str]:
    return re.findall(r"'([^']+)'", block)


def _flat(value: str) -> str:
    return _WHITESPACE.sub(" ", value)


def _joined(source: str) -> str:
    """The source with adjacent string literals joined, whitespace flattened."""
    return _flat(re.sub(r"\"\s*\n\s*\"", "", source))


def _module(path: Path = MIGRATION) -> dict[str, object]:
    """A revision's module namespace (it imports only `alembic` and `typing`)."""
    namespace: dict[str, object] = {}
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), namespace)  # noqa: S102
    return namespace


def _balanced(value: str, start: int) -> str:
    """The parenthesised text opening at `value[start]`, without its parentheses."""
    depth = 0
    for index in range(start, len(value)):
        if value[index] == "(":
            depth += 1
        elif value[index] == ")":
            depth -= 1
            if depth == 0:
                return value[start + 1 : index]
    raise AssertionError("unbalanced CHECK text")


def _left_text(table: str, name: str) -> str | None:
    """The CHECK text `c5260943d933` leaves: the latest earlier revision's own."""
    left: str | None = None
    for path in EARLIER:
        module = _module(path)
        for widened_table, widened, _before, after in module.get("_WIDENED_CHECKS", ()):  # type: ignore[attr-defined]
            if (widened_table, widened) == (table, name):
                left = str(after)
        for added_table, added, expression in module.get("_ADDED_CHECKS", ()):  # type: ignore[attr-defined]
            if (added_table, added) == (table, name):
                left = str(expression)
        for key in ("_TABLE_DDL", "_CLOCK_DDL"):
            for created, ddl in module.get(key, ()):  # type: ignore[attr-defined]
                if created != table:
                    continue
                flat = _flat(str(ddl))
                marker = f"CONSTRAINT {name} CHECK "
                found = flat.find(marker)
                if found >= 0:
                    left = _balanced(flat, found + len(marker))
    return left


def _left_function_body(name: str) -> str:
    """The body `c5260943d933` leaves for one function: its latest creation or replacement."""
    left: str | None = None
    for path in EARLIER:
        module = _module(path)
        for created in module.get("_FUNCTIONS", ()):  # type: ignore[attr-defined]
            if created[0] == name:
                left = str(created[1])
        for replaced in module.get("_REPLACED_FUNCTIONS", ()):  # type: ignore[attr-defined]
            if replaced[0] == name:
                left = str(replaced[1])
    assert left is not None, name
    return left.split("$$", 1)[1].rsplit("$$", 1)[0]


