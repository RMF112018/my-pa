    with engine.begin() as connection:
        connection.execute(
            insert(issue_responsibility_events).values(
                **_handoff(world, commitment_id, 1, from_entity=entity, to_entity=None)
            )
        )
    with engine.connect() as connection:
        before = _rows(connection)
        latest = dict(
            connection.execute(
                text(
                    "SELECT principal_id, max(recorded_at) FROM ("
                    "SELECT principal_id, recorded_at FROM knowledge.issue_revisions UNION ALL "
                    "SELECT principal_id, recorded_at FROM "
                    "knowledge.issue_project_membership_events UNION ALL "
                    "SELECT principal_id, recorded_at FROM knowledge.record_link_revisions "
                    "UNION ALL SELECT principal_id, recorded_at FROM "
                    "knowledge.issue_responsibility_events) facts GROUP BY principal_id"
                )
            ).all()
        )
    assert all(before[table] for table in ("issue_revisions", "issue_responsibility_events"))
    command.upgrade(_config(), REVISION)
    _assert_present(engine)
    with engine.connect() as connection:
        after = _rows(connection)
        seeded = {
            row.principal_id: (row.last_seq, row.last_marked_at)
            for row in connection.execute(text("SELECT * FROM knowledge.lineage_commit_sequences"))
        }
        marks = connection.execute(
            text("SELECT count(*) FROM knowledge.lineage_commit_marks")
        ).scalar_one()
        unmarked = {
            table: set(
                connection.execute(
                    text(f"SELECT DISTINCT commit_seq FROM knowledge.{table}")  # noqa: S608
                ).scalars()
            )
            for table in (
                "issue_revisions",
                "issue_project_membership_events",
                "record_link_revisions",
                "issue_responsibility_events",
                "lineage_write_requests",
            )
        }
    for table, rows in before.items():
        # The S2 columns of every row are unchanged; added columns come last.
        assert [row[: len(rows[0])] for row in after[table]] == rows, table
    assert all(values == {None} for values in unmarked.values()), unmarked
    # One allocator row per Principal with any fact row: sequence 0 at the
    # greatest recorded_at of its facts -- the horizon pre-S3 facts are known
    # under. No mark exists yet.
    assert seeded == {principal: (0, recorded) for principal, recorded in latest.items()}
    assert set(seeded) == {P, other.principal}
    assert marks == 0
    # The next lineage write takes mark 1, later than the seeded horizon.
    with engine.begin() as connection:
        mark = connection.execute(
            text("SELECT knowledge.lineage_commit_mark(:p)"), {"p": P}
        ).scalar_one()
        marked = connection.execute(
            text("SELECT marked_at FROM knowledge.lineage_commit_marks WHERE principal_id = :p"),
            {"p": P},
        ).scalar_one()
    assert mark == 1
    assert marked > seeded[P][1]


