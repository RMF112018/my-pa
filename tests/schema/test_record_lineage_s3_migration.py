def test_frozen_ddl_names_every_declared_constraint() -> None:
    """The revision's text and `tables.py` name the same S3 schema objects.

    Parity of the definitions is proved on a server by
    `tests/database/test_lineage_s3_integrity_guards.py` and
    `tests/database/test_lineage_commit_marks.py`; this is the static half.
    """
    source = MIGRATION.read_text(encoding="utf-8")
    earlier = S1_MIGRATION.read_text(encoding="utf-8") + S2_MIGRATION.read_text(encoding="utf-8")
    flat = _joined(source)
    for table in NEW_TABLES:
        assert f"CREATE TABLE knowledge.{table.name} (" in source
        for column in table.c:
            assert re.search(rf"\b{column.name}\b", source), (table.name, column.name)
        for constraint in table.constraints:
            if constraint.name is not None and not str(constraint.name).startswith("_"):
                assert str(constraint.name) in source, (table.name, constraint.name)
        for index in table.indexes:
            assert f"INDEX {index.name} ON knowledge.{table.name}" in flat, index.name
    for table in ALTERED_TABLES:
        for column in ADDED_COLUMNS.get(table.name, frozenset()):
            assert column in table.c, (table.name, column)
            assert f"ALTER TABLE knowledge.{table.name} ADD COLUMN {column} " in source
        declared = {str(c.name) for c in table.constraints if c.name}
        # Every name the S1 and S2 revisions do not create is this revision's.
        for name in declared:
            if name not in earlier:
                assert name in source, (table.name, name)
        for name in WIDENED.get(table.name, frozenset()):
            assert name in declared and name in earlier and name in source, (table.name, name)
        for index in table.indexes:
            if f"INDEX {index.name} " not in _flat(earlier):
                assert f"INDEX {index.name} ON knowledge.{table.name}" in flat, index.name
    for function in FUNCTIONS | set(REPLACED_FUNCTIONS):
        assert f"knowledge.{function}(" in flat, function
    for table_name, trigger in TRIGGERS:
        assert trigger in source, (table_name, trigger)
    # The one-live-head index is recreated under its name, over both live states.
    assert "WHERE lifecycle_state IN ('active', 'contested')" in flat
    assert "record_link_one_active_identity" in source


def _s2_text(name: str, table: str) -> str | None:
    """The text `d020b532ad7d` leaves for one CHECK: S2's own, or S1's."""
    s2 = _module(S2_MIGRATION)
    for widened_table, widened, _before, after in s2["_WIDENED_CHECKS"]:  # type: ignore[attr-defined]
        if (widened_table, widened) == (table, name):
            return str(after)
    for added_table, added, expression in s2["_ADDED_CHECKS"]:  # type: ignore[attr-defined]
        if (added_table, added) == (table, name):
            return str(expression)
    return None


def test_before_texts_are_byte_copies_of_the_s2_texts() -> None:
    """Copied, not reconstructed: the texts `downgrade` restores are what S2 left."""
    source = MIGRATION.read_text(encoding="utf-8")
    s2 = S2_MIGRATION.read_text(encoding="utf-8")
    s1 = S1_MIGRATION.read_text(encoding="utf-8")
    assert _constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION") == _constant(
        s2, "_CAPABILITIES_AT_THIS_REVISION"
    )
    assert _constant(source, "_PURPOSES_BEFORE_THIS_REVISION") == _constant(
        s2, "_PURPOSES_AT_THIS_REVISION"
    )
    module = _module()
    widened = module["_WIDENED_CHECKS"]
    assert isinstance(widened, tuple)
    assert {(table, name) for table, name, _, _ in widened} == {
        (table, name) for table, names in WIDENED.items() for name in names
    }
    flat_s1 = _flat(s1)
    for table, name, before, after in widened:
        s2_text = _s2_text(name, table)
        if s2_text is not None:
            assert before == s2_text, name
        else:
            # S1 wraps its CHECKs inside `CREATE TABLE`; whitespace aside, the
            # restored text is the one it created.
            assert f"CONSTRAINT {name} CHECK ({before})" in flat_s1, name
        assert before != after
    replaced = module["_REPLACED_FUNCTIONS"]
    assert isinstance(replaced, tuple)
    assert tuple(name for name, _, _ in replaced) == REPLACED_FUNCTIONS
    s2_module = _module(S2_MIGRATION)
    s2_current = {
        name: current
        for name, current, _previous in s2_module["_REPLACED_FUNCTIONS"]  # type: ignore[attr-defined]
    }
    s2_created = dict(s2_module["_FUNCTIONS"])  # type: ignore[call-overload]
    for name, current, previous in replaced:
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in current
        assert f"CREATE OR REPLACE FUNCTION knowledge.{name}()" in previous
        body = previous.split("$$", 1)[1].rsplit("$$", 1)[0]
        # The body is the one `d020b532ad7d` leaves: its own replacement, its own
        # creation, or (for a function S2 did not touch) S1's.
        left = s2_current.get(name) or s2_created.get(name)
        if left is not None:
            assert f"$${body}$$" in str(left), name
        else:
            assert f"$${body}$$" in s1, name
        assert current.split("$$", 1)[1] != previous.split("$$", 1)[1]
    # The one-live-head index: S1's text restored, both live states at S3.
    assert module["_ONE_LIVE_HEAD_BEFORE"] in _flat(s1)
    assert "IN ('active', 'contested')" in str(module["_ONE_LIVE_HEAD_AT"])
    script = ScriptDirectory.from_config(_config())
    assert script.get_revision(REVISION).down_revision == PREVIOUS


