def _s2_texts(engine: Engine) -> dict[str, object]:
    """Every S2 text the revision touches: the CHECKs, bodies, index and columns."""
    names = sorted(name for names in WIDENED.values() for name in names)
    with engine.connect() as connection:
        checks = dict(
            connection.execute(
                text(
                    "SELECT c.relname || '.' || con.conname, pg_get_constraintdef(con.oid) "
                    "FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace "
                    "WHERE n.nspname = :schema AND con.conname = ANY(:names)"
                ),
                {"schema": SCHEMA, "names": names},
            ).all()
        )
        audit = dict(
            connection.execute(
                text(
                    "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                    "WHERE con.conrelid = 'knowledge.audit_events'::regclass "
                    "AND con.conname IN ('capability_is_known', 'purpose_is_known')"
                )
            ).all()
        )
        functions = dict(
            connection.execute(
                text(
                    "SELECT p.proname, pg_get_functiondef(p.oid) FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace "
                    "WHERE n.nspname = :schema AND p.proname = ANY(:names)"
                ),
                {"schema": SCHEMA, "names": list(REPLACED_FUNCTIONS)},
            ).all()
        )
        index = connection.execute(
            text(
                "SELECT indexdef FROM pg_indexes WHERE schemaname = :schema "
                "AND indexname = 'record_link_one_active_identity'"
            ),
            {"schema": SCHEMA},
        ).scalar_one()
        columns = sorted(
            connection.execute(
                text(
                    "SELECT table_name || '.' || column_name || ' ' || data_type || ' ' || "
                    "is_nullable || ' ' || coalesce(column_default, '') "
                    "FROM information_schema.columns WHERE table_schema = :schema "
                    "AND table_name = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": [table.name for table in ALTERED_TABLES]},
            ).scalars()
        )
        constraint_names = sorted(
            connection.execute(
                text(
                    "SELECT c.relname || '.' || con.conname FROM pg_constraint con "
                    "JOIN pg_class c ON c.oid = con.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = :schema "
                    "AND c.relname = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": [table.name for table in ALTERED_TABLES]},
            ).scalars()
        )
        index_names = sorted(
            connection.execute(
                text(
                    "SELECT tablename || '.' || indexname FROM pg_indexes "
                    "WHERE schemaname = :schema AND tablename = ANY(:tables)"
                ),
                {"schema": SCHEMA, "tables": [table.name for table in ALTERED_TABLES]},
            ).scalars()
        )
    assert len(checks) == len(names) and len(functions) == len(REPLACED_FUNCTIONS)
    return {
        "checks": checks,
        "audit": audit,
        "functions": functions,
        "index": index,
        "columns": columns,
        "constraints": constraint_names,
        "indexes": index_names,
    }


