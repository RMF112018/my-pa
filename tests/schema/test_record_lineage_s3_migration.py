def _replica(connection: Connection) -> None:
    """Silence every trigger (foreign keys, the mark, deferred checks) for this transaction.

    Each refusal case seeds exactly one S3 fact; several cannot exist alone
    while their triggers run (a mark without its allocation, a correction
    without its handoff, any fact row without its own mark). CHECKs still
    apply. The disposable database's role is its superuser.
    """
    connection.execute(text("SET LOCAL session_replication_role = replica"))


def _seed(statement: str, values: dict[str, object] | None = None) -> Callable[[Engine], None]:
    def seed(engine: Engine) -> None:
        with engine.begin() as connection:
            _replica(connection)
            connection.execute(text(statement), {"p": P, **(values or {})})

    return seed


