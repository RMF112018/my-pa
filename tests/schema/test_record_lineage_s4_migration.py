def test_the_revision_imports_no_domain_module() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    imported: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and node.module is not None:
            imported.add(node.module)
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert imported <= {"alembic", "__future__", "typing"}
    assert "my_pa" not in source
    assert "create_all" not in source
    code = source.split('"""', 2)[2].upper()
    for statement in ("DELETE FROM", "UPDATE KNOWLEDGE", "GRANT ", "INSERT INTO"):
        assert statement not in code
    # No existing table gains a column or an index (section 4).
    assert "ADD COLUMN" not in code
    assert "CREATE INDEX" not in code and "CREATE UNIQUE INDEX" not in code


def test_frozen_ddl_names_every_declared_constraint() -> None:
    """The revision's text and `tables.py` name the same S4 schema objects.

    Parity of the definitions is proved on a server by
    `tests/database/test_lineage_s4_integrity_guards.py`; this is the static half.
    """
    source = MIGRATION.read_text(encoding="utf-8")
    flat = _flat(re.sub(r"\"\s*\n\s*\"", "", source))
    table = intelligence_artifact_manifests
    assert f"CREATE TABLE knowledge.{table.name} (" in source
    for column in table.c:
        assert re.search(rf"\b{column.name}\b", source), column.name
    for constraint in table.constraints:
        if constraint.name is not None and not str(constraint.name).startswith("_"):
            assert f"CONSTRAINT {constraint.name} " in flat, constraint.name
    assert not table.indexes
    for function in FUNCTIONS:
        assert f"CREATE FUNCTION knowledge.{function}()" in source, function
    for table_name, trigger in TRIGGERS:
        assert f"TRIGGER {trigger} " in flat, trigger
        assert f"ON knowledge.{table_name} " in flat, table_name
    assert (
        "CREATE CONSTRAINT TRIGGER an_artifact_has_its_manifest AFTER INSERT ON "
        "knowledge.intelligence_artifacts DEFERRABLE INITIALLY DEFERRED" in flat
    )
    # The existing S1-era function, reused rather than restated.
    assert "EXECUTE FUNCTION knowledge.intelligence_lineage_is_append_only()" in flat
    assert "CREATE FUNCTION knowledge.intelligence_lineage_is_append_only" not in source


