def test_at_vocabulary_adds_exactly_the_s4_names() -> None:
    source = MIGRATION.read_text(encoding="utf-8")
    before = _literals(_constant(source, "_CAPABILITIES_BEFORE_THIS_REVISION"))
    at = _literals(_constant(source, "_CAPABILITIES_AT_THIS_REVISION"))
    assert set(at) == set(before) | S4_CAPABILITIES
    assert len(at) == len(before) + len(S4_CAPABILITIES) == 240
    assert at == sorted(at)
    purposes_before = _literals(_constant(source, "_PURPOSES_BEFORE_THIS_REVISION"))
    purposes_at = _literals(_constant(source, "_PURPOSES_AT_THIS_REVISION"))
    assert set(purposes_at) == set(purposes_before) | S4_PURPOSES
    assert len(purposes_at) == len(purposes_before) + len(S4_PURPOSES) == 60
    assert purposes_at == sorted(purposes_at)
    # The head admits every declared name, and the S4 schema-ahead gap is
    # exactly the S4 names the domain does not declare yet (none).
    # The S3.1 names, declared since, are the S3.1 revision's (023f8f7eb499).
    declared = {capability.value for capability in Capability} - S31_CAPABILITIES
    native = {capability.value for capability in NativeSourceCapability}
    assert set(at) == declared | native | gap.lineage_s4_admitted_ahead("capability")
    purposes = {purpose.value for purpose in Purpose}
    assert set(purposes_at) == purposes | gap.lineage_s4_admitted_ahead("purpose")
    assert S4_CAPABILITIES & declared == gap.S4_CAPABILITIES_DECLARED_BY_DOMAIN
    assert S4_PURPOSES & purposes == gap.S4_PURPOSES_DECLARED_BY_DOMAIN
    assert gap.LINEAGE_S4_DECLARED_BY_DOMAIN is (
        declared >= S4_CAPABILITIES and purposes >= S4_PURPOSES
    )
    assert gap.lineage_s4_admitted_ahead("capability") == frozenset()
    assert gap.lineage_s4_admitted_ahead("purpose") == frozenset()
    assert len(S4_CAPABILITIES) == 7
    assert len(S4_PURPOSES) == 1


# ---- offline SQL -------------------------------------------------------------


def _offline(target: str, *, down: bool = False) -> str:
    buffer = io.StringIO()
    action = command.downgrade if down else command.upgrade
    action(_config(buffer), target, sql=True)
    return _flat(buffer.getvalue())


def test_offline_downgrade_refuses_first(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    refusal = rendered.index(REFUSAL)
    for name in NEW_TABLE_NAMES:
        assert rendered.index(f"DROP TABLE knowledge.{name} RESTRICT") > refusal
    for table, trigger in TRIGGERS:
        assert rendered.index(f"DROP TRIGGER {trigger} ON knowledge.{table}") > refusal
    for function in FUNCTIONS:
        assert rendered.index(f"DROP FUNCTION knowledge.{function}()") > refusal
    after = rendered.split("ADD CONSTRAINT capability_is_known CHECK")[1]
    assert "'programs.overview'" not in after
    assert f"SET version_num='{PREVIOUS}'" in rendered
    upgraded = _offline(f"{PREVIOUS}:{REVISION}")
    assert "'programs.members.resolve', 'programs.overview'" in upgraded
    assert f"SET version_num='{REVISION}'" in upgraded


