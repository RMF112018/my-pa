def _catalog(engine: Engine) -> dict[str, set[str]]:
    with engine.connect() as connection:
        rows = {
            "tables": "SELECT tablename FROM pg_tables WHERE schemaname = :schema",
            "triggers": (
                "SELECT c.relname || '.' || t.tgname FROM pg_trigger t "
                "JOIN pg_class c ON c.oid = t.tgrelid "
                "JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE NOT t.tgisinternal AND n.nspname = :schema"
            ),
            "functions": (
                "SELECT p.proname FROM pg_proc p "
                "JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = :schema"
            ),
        }
        catalog = {
            key: set(connection.execute(text(query), {"schema": SCHEMA}).scalars())
            for key, query in rows.items()
        }
        catalog["version"] = set(
            connection.execute(text("SELECT version_num FROM alembic_version")).scalars()
        )
    return catalog


def _assert_present(engine: Engine, *, at: str = HEAD) -> None:
    catalog = _catalog(engine)
    assert catalog["version"] == {at}
    assert catalog["tables"] >= NEW_TABLE_NAMES
    assert catalog["functions"] >= FUNCTIONS
    assert {f"{table}.{trigger}" for table, trigger in TRIGGERS} <= catalog["triggers"]


def _assert_absent(engine: Engine) -> None:
    catalog = _catalog(engine)
    assert catalog["version"] == {PREVIOUS}
    assert not catalog["tables"] & NEW_TABLE_NAMES
    assert not catalog["functions"] & FUNCTIONS
    assert not {f"{table}.{trigger}" for table, trigger in TRIGGERS} & catalog["triggers"]


def _audit(connection: Connection, *, capability: str, purpose: str, suffix: str) -> None:
    connection.execute(
        insert(audit_events).values(
            audit_id=f"audit_{suffix}",
            correlation_id=f"corr_{suffix}",
            principal_id=P,
            capability=capability,
            purpose=purpose,
            outcome="allowed",
            policy_version="policy-v1",
            scope_source_id_count=0,
            recorded_at=WHEN,
        )
    )


def _replica(connection: Connection) -> None:
    """Silence every trigger and foreign key for this transaction (the S3 precedent).

    The disposable database's role is its superuser; CHECKs still apply.
    """
    connection.execute(text("SET LOCAL session_replication_role = replica"))


