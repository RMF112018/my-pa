def _s3_texts(engine: Engine) -> dict[str, object]:
    """Every S3 text the revision touches: the audit CHECKs and the artifact triggers."""
    with engine.connect() as connection:
        audit = dict(
            connection.execute(
                text(
                    "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                    "WHERE con.conrelid = 'knowledge.audit_events'::regclass "
                    "AND con.conname IN ('capability_is_known', 'purpose_is_known')"
                )
            ).all()
        )
        triggers = sorted(
            connection.execute(
                text(
                    "SELECT t.tgname || ' ' || pg_get_triggerdef(t.oid) FROM pg_trigger t "
                    "WHERE t.tgrelid = 'knowledge.intelligence_artifacts'::regclass "
                    "AND NOT t.tgisinternal"
                )
            ).scalars()
        )
        constraints = sorted(
            connection.execute(
                text(
                    "SELECT con.conname || ' ' || pg_get_constraintdef(con.oid) "
                    "FROM pg_constraint con "
                    "WHERE con.conrelid = 'knowledge.intelligence_artifacts'::regclass "
                    # A constraint trigger has a `pg_constraint` row too; it is
                    # compared with the triggers above.
                    "AND con.contype <> 't'"
                )
            ).scalars()
        )
    return {"audit": audit, "triggers": triggers, "constraints": constraints}


@pytest.mark.database
@pytest.mark.migration
def test_downgrade_restores_every_s3_text(disposable_database: str, engine: Engine) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    at_s3 = _s3_texts(engine)
    command.upgrade(_config(), REVISION)
    at_s4 = _s3_texts(engine)
    for key in ("audit", "triggers"):
        assert at_s4[key] != at_s3[key], key
    assert at_s4["constraints"] == at_s3["constraints"]
    command.downgrade(_config(), PREVIOUS)
    _assert_absent(engine)
    assert _s3_texts(engine) == at_s3
    # Back to this revision: the S3.1 revision restates the audit text again.
    command.upgrade(_config(), REVISION)
    _assert_present(engine, at=REVISION)
    assert _s3_texts(engine) == at_s4


