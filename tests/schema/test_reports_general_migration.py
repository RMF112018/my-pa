@pytest.mark.database
def test_the_transition_check_admits_exactly_the_domain_rule(plane_engine: Engine) -> None:
    """Every `(operation, prior, resulting)` the CHECK admits is a domain-applied transition."""
    applied: set[tuple[str, str, str]] = set()
    for state in LifecycleState:
        for operation in LifecycleOperation:
            sources = (
                (LifecycleState.ACTIVE, LifecycleState.ARCHIVED)
                if state is LifecycleState.TRASHED
                else (None,)
            )
            for trashed_from in sources:
                try:
                    decision = decide_lifecycle_transition(
                        state, operation, trashed_from=trashed_from
                    )
                except ReportLifecycleRefusal:
                    continue
                if decision.outcome is ReceiptOutcome.APPLIED:
                    applied.add((operation.value, state.value, decision.resulting_state.value))
    with plane_engine.connect() as connection:
        definition = connection.execute(
            text(
                "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conname = 'a_report_lifecycle_transition_is_valid'"
            )
        ).scalar_one()
        expression = str(definition).removeprefix("CHECK ")
        admitted = {
            (str(o), str(p), str(r))
            for o, p, r in connection.execute(
                text(
                    "SELECT operation, prior_state, resulting_state "  # noqa: S608
                    "FROM unnest(CAST(:o AS text[])) operation "
                    "CROSS JOIN unnest(CAST(:s AS text[])) prior_state "
                    "CROSS JOIN unnest(CAST(:s AS text[])) resulting_state "
                    f"WHERE {expression}"
                ),
                {"o": _values(LifecycleOperation), "s": _values(LifecycleState)},
            )
        }
    assert admitted == applied


