def _statement(op: Op) -> tuple[str, dict[str, object]]:
    if op.sql is not None:
        return op.sql, dict(op.values)
    params = {
        column: json.dumps(value) if column in _JSON_COLUMNS and value is not None else value
        for column, value in op.values.items()
    }

    def placeholder(column: str) -> str:
        return f"CAST(:{column} AS jsonb)" if column in _JSON_COLUMNS else f":{column}"

    if op.key is None:
        columns = ", ".join(op.values)
        values = ", ".join(placeholder(column) for column in op.values)
        return f"INSERT INTO {SCHEMA}.{op.table} ({columns}) VALUES ({values})", params  # noqa: S608
    assignments = ", ".join(f"{column} = {placeholder(column)}" for column in op.values)
    params["_key"] = op.key[1]
    return (
        f"UPDATE {SCHEMA}.{op.table} SET {assignments} WHERE {op.key[0]} = :_key",  # noqa: S608
        params,
    )


def _execute(engine: Engine, ops: list[Op]) -> None:
    """One transaction; a refusal raises from its statement or from the commit."""
    with engine.begin() as connection:
        for op in ops:
            statement, params = _statement(op)
            connection.execute(text(statement), params)


Change = Mapping[str, Mapping[str, object] | None]


def _changed(ops: list[Op], change: Change, foreign: dict[str, str] | None) -> list[Op]:
    labels = {op.label for op in ops}
    assert set(change) <= labels, (sorted(change), sorted(labels))
    result: list[Op] = []
    for op in ops:
        if op.label not in change:
            result.append(op)
            continue
        fields = change[op.label]
        if fields is None:
            continue
        resolved: dict[str, object] = {}
        for column, value in fields.items():
            if isinstance(value, Foreign):
                assert foreign is not None
                value = foreign[value.key]
            resolved[column] = value
        assert set(resolved) <= set(op.values) or op.key is not None, (op.label, resolved)
        result.append(Op(op.label, op.table, {**op.values, **resolved}, op.key, op.sql))
    return result


def _needs_foreign(change: Change) -> bool:
    return any(
        isinstance(value, Foreign)
        for fields in change.values()
        if fields is not None
        for value in fields.values()
    )


@dataclass(frozen=True)
class Expect:
    sqlstate: str
    constraint: str | None = None
    table: str | None = None
    message: str | None = None


def _check(table: str, name: str) -> Expect:
    return Expect(CHECK_VIOLATION, name, table)


def _fk(table: str, name: str) -> Expect:
    return Expect(FOREIGN_KEY_VIOLATION, name, table)


def _unique(table: str, name: str) -> Expect:
    return Expect(UNIQUE_VIOLATION, name, table)


def _refused(message: str, sqlstate: str = RESTRICT_VIOLATION) -> Expect:
    return Expect(sqlstate, message=message)


@dataclass(frozen=True)
class Case:
    """From the committed baseline `chain`, one mutation only `expect` can refuse.

    `change` alters the chain's last transaction (the baseline commits without
    it); `then` is one further transaction after the whole chain commits.
    """

    id: str
    chain: str
    expect: Expect
    change: Change = field(default_factory=dict)
    then: Callable[[dict[str, str]], list[Op]] | None = None


def _attempt(engine: Engine, case: Case, *, mutated: bool) -> DBAPIError | None:
    """Write the case's baseline (and, when `mutated`, its mutation); return the refusal."""
    tag = uuid.uuid4().hex[:16]
    foreign: dict[str, str] | None = None
    if mutated and _needs_foreign(case.change):
        foreign = _ids(f"{tag}q", Q)
        # The foreign report holds no association and no receipt, so a
        # foreign-version association, or a receipt naming a foreign version or
        # event, can only meet the owner-scoped reference (not the applied-once
        # indexes, which a foreign receipt for the same version would meet first).
        for name in CHAINS["archive"]:
            ops = _TRANSACTIONS[name](foreign)
            _execute(
                engine,
                [
                    op
                    for op in ops
                    if not op.label.startswith("association") and op.label != "receipt"
                ],
            )
    ids = _ids(tag, P)
    transactions = [_TRANSACTIONS[name](ids) for name in CHAINS[case.chain]]
    if mutated and case.then is not None:
        transactions.append(case.then(ids))
    elif mutated:
        transactions[-1] = _changed(transactions[-1], case.change, foreign)
    for number, transaction in enumerate(transactions):
        try:
            _execute(engine, transaction)
        except DBAPIError as error:
            assert number == len(transactions) - 1, (
                f"the baseline failed before the mutation: {error.orig}"
            )
            return error
    return None


def _assert_refused(error: DBAPIError | None, expect: Expect) -> None:
    assert error is not None, "the mutation committed"
    orig = error.orig
    diag = getattr(orig, "diag", None)
    assert getattr(orig, "sqlstate", None) == expect.sqlstate, str(orig)
    if expect.constraint is not None:
        assert diag is not None
        assert diag.constraint_name == expect.constraint, str(orig)
        assert diag.table_name == expect.table, str(orig)
    if expect.message is not None:
        assert diag is not None
        assert expect.message in (diag.message_primary or ""), str(orig)


def _raw(label: str, table: str, sql: str, **params: object) -> Op:
    return Op(label, table, params, sql=sql)


def _reinsert(
    chain: str, label: str, column: str, value: str, *, with_manifest: bool = False
) -> Callable[[dict[str, str]], list[Op]]:
    """The committed `label` row of `chain`, inserted again with only `column` changed.

    `with_manifest` re-inserts the version's manifest alike, so the copy is a
    whole version and only the UNIQUE under test can refuse it.
    """

    def build(ids: dict[str, str]) -> list[Op]:
        ops = [op for name in CHAINS[chain] for op in _TRANSACTIONS[name](ids)]
        labels = (label, "manifest") if with_manifest else (label,)
        return [
            Op(found.label, found.table, {**found.values, column: ids[value]})
            for found in (
                next(op for op in reversed(ops) if op.label == wanted) for wanted in labels
            )
        ]

    return build


