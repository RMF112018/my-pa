def _evidence(engine: Engine) -> dict[str, tuple[int, str]]:
    """Per table: its row count and an order-independent digest of its rows."""
    with engine.connect() as connection:
        found: dict[str, tuple[int, str]] = {}
        for qualified in _user_tables(connection):
            schema, table = qualified.split(".", 1)
            query = (
                "SELECT count(*), md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), '')) "  # noqa: S608
                f'FROM "{schema}"."{table}" AS t'
            )
            count, digest = connection.execute(text(query)).one()
            found[qualified] = (int(count), str(digest))
        return found


