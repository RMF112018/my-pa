def _ddl_columns(ddl: str) -> list[tuple[str, bool]]:
    # A generated column (`search_document TSVECTOR GENERATED ALWAYS AS (...)
    # STORED`, WP04) is nullable and spelled with its expression.
    return [
        (match.group(1), match.group(2) is None)
        for match in re.finditer(
            r"^\s+(\w+) (?:TEXT|INTEGER|BOOLEAN|JSONB|BYTEA|DATE|TIMESTAMP WITH TIME ZONE|TSVECTOR)"
            r"( NOT NULL)?(?:,| GENERATED ALWAYS AS \(.*\) STORED,)$",
            ddl,
            re.MULTILINE,
        )
    ]


def _created_names() -> dict[str, set[str]]:
    module = _module()
    created: dict[str, set[str]] = {}
    for name, ddl, indexes in module["_TABLES"]:  # type: ignore[attr-defined]
        found = set(re.findall(r"CONSTRAINT (\w+)", _flat(str(ddl))))
        found |= {re.search(r"INDEX (\w+)", index).group(1) for index in indexes}  # type: ignore[union-attr]
        created[str(name)] = found
    for name, _definition in module["_DEFERRED_FOREIGN_KEYS"]:  # type: ignore[attr-defined]
        created["report_roots"].add(str(name))
    return created


