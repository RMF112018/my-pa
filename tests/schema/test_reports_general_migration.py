def _content(ids: dict[str, str], key: str, variant: str = "md") -> Op:
    body = f"Synthetic report body {ids[key]}"
    decoded = body.encode()
    row: dict[str, object] = {
        "content_id": ids[key],
        "owner_principal_id": ids["owner"],
        "format": "markdown",
        "original_encoding": "identity",
        "storage_kind": "inline",
        "original_sha256": _sha(decoded),
        "original_byte_count": len(decoded),
        "decoded_sha256": _sha(decoded),
        "decoded_byte_count": len(decoded),
        "canonical_sha256": None,
        "inline_text": body,
        "inline_data": None,
        "inline_original": None,
        "blob_ref": None,
        "created_at": NOW,
    }
    if variant in ("gz", "gzblob"):
        original = base64.b64encode(gzip.compress(decoded, mtime=0))
        row |= {
            "original_encoding": "gzip+base64",
            "original_sha256": _sha(original),
            "original_byte_count": len(original),
            "inline_original": original,
        }
    if variant == "json":
        data = {"synthetic": ids[key]}
        canonical = json.dumps(data, sort_keys=True, separators=(",", ":")).encode()
        row |= {
            "format": "json",
            "inline_text": None,
            "inline_data": data,
            "original_sha256": _sha(canonical),
            "original_byte_count": len(canonical),
            "decoded_sha256": _sha(canonical),
            "decoded_byte_count": len(canonical),
            "canonical_sha256": _sha(canonical),
        }
    if variant == "mixed":
        row |= {"format": "mixed", "inline_data": {"synthetic": ids[key]}}
    if variant in ("blob", "gzblob"):
        row |= {
            "storage_kind": "managed_blob",
            "inline_text": None,
            "inline_original": None,
            "blob_ref": f"blobs/{ids[key]}",
        }
    return Op("content", "report_content_objects", row)


