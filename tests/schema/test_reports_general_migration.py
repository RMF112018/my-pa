def _offline(target: str, *, down: bool = False) -> str:
    buffer = io.StringIO()
    action = command.downgrade if down else command.upgrade
    action(_config(buffer), target, sql=True)
    return _flat(buffer.getvalue())


def test_offline_upgrade_writes_no_row_and_names_only_the_plane(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{PREVIOUS}:{REVISION}")
    body = rendered[rendered.index(f"Running upgrade {PREVIOUS} -> {REVISION}") :]
    assert body.index("SET LOCAL lock_timeout = '10s'") < body.index("CREATE TABLE")
    assert "CASCADE" not in body.upper()
    assert not re.search(r"\b(GRANT|REVOKE)\b", body)
    for statement in re.split(r";\s", body):
        if "alembic_version" in statement:
            continue
        assert not re.match(r"\s*(INSERT|UPDATE|DELETE|COPY|TRUNCATE)\b", statement), statement[
            :120
        ]
    # Quoted capability names (`'knowledge.read'`) are values, not relations.
    named = set(re.findall(r"(?<!')\bknowledge\.(\w+)", body))
    assert named == set(PLANE_TABLES) | set(PLANE_FUNCTIONS) | {"audit_events"}, sorted(named)
    # `audit_events` is named only by the two restatements, after every plane object.
    touching = [statement for statement in re.split(r";\s", body) if "audit_events" in statement]
    expected_statements = (
        "ALTER TABLE knowledge.audit_events DROP CONSTRAINT capability_is_known",
        "ALTER TABLE knowledge.audit_events ADD CONSTRAINT capability_is_known CHECK",
        "ALTER TABLE knowledge.audit_events DROP CONSTRAINT purpose_is_known",
        "ALTER TABLE knowledge.audit_events ADD CONSTRAINT purpose_is_known CHECK",
    )
    assert len(touching) == len(expected_statements), touching
    for statement, prefix in zip(touching, expected_statements, strict=True):
        assert _flat(statement).strip().startswith(prefix), statement[:120]
    assert body.rindex("CREATE TRIGGER") < body.index("knowledge.audit_events")
    # The only cross-table references are the plane's own.
    for target in re.findall(r"REFERENCES (\S+)", body):
        assert target.removeprefix("knowledge.") in PLANE_TABLES, target
    assert f"UPDATE alembic_version SET version_num='{REVISION}'" in body  # noqa: S608


def test_offline_downgrade_locks_and_refuses_before_any_drop(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    refusal = rendered.index(REFUSAL)
    lock = rendered.index("LOCK TABLE knowledge.report_content_objects,")
    assert rendered.index("SET LOCAL lock_timeout = '10s'") < lock < refusal
    locked = rendered[lock : rendered.index("IN ACCESS EXCLUSIVE MODE", lock)]
    assert all(f"knowledge.{table}" in locked for table in PLANE_TABLES), locked
    first_drop = min(
        rendered.index(statement)
        for statement in (
            "DROP TRIGGER",
            "DROP FUNCTION",
            "DROP TABLE",
            "DROP CONSTRAINT",
            "ALTER TABLE knowledge.report_roots DROP CONSTRAINT",
        )
    )
    first_plane_drop = min(
        rendered.index(statement)
        for statement in (
            "DROP TRIGGER",
            "DROP FUNCTION",
            "DROP TABLE",
            "ALTER TABLE knowledge.report_roots DROP CONSTRAINT",
        )
    )
    assert refusal < first_drop
    # The audit refusal is in the same block; the BEFORE text is restored after
    # it and before any plane object is dropped.
    assert rendered.index(AUDIT_REFUSAL) < rendered.index(
        "ALTER TABLE knowledge.audit_events DROP CONSTRAINT capability_is_known"
    )
    restore = rendered.index(
        "ALTER TABLE knowledge.audit_events ADD CONSTRAINT capability_is_known"
    )
    purposes_restore = rendered.index(
        "ALTER TABLE knowledge.audit_events ADD CONSTRAINT purpose_is_known"
    )
    assert refusal < first_drop < restore < purposes_restore < first_plane_drop
    restored = rendered[restore : rendered.index(";", restore)]
    for name in ADMITTED_CAPABILITIES:
        assert f"'{name}'" not in restored, name
    restored_purposes = rendered[purposes_restore : rendered.index(";", purposes_restore)]
    assert "'report_authoring'" in restored_purposes
    for name in ADMITTED_PURPOSES:
        assert f"'{name}'" not in restored_purposes, name
    for table in PLANE_TABLES:
        assert rendered.index(f"DROP TABLE knowledge.{table} RESTRICT") > refusal
    # The deferred foreign keys go before the tables.
    for name in DEFERRED_FOREIGN_KEYS:
        assert rendered.index(f"DROP CONSTRAINT {name}") < rendered.index("DROP TABLE")
    assert f"SET version_num='{PREVIOUS}'" in rendered


