def _definitions(
    engine: Engine, schema: str, names: tuple[str, ...]
) -> dict[str, dict[str, list[tuple[str, ...]]]]:
    snapshot: dict[str, dict[str, list[tuple[str, ...]]]] = {}
    with engine.connect() as connection:
        for table in names:
            snapshot[table] = {
                kind: sorted(
                    tuple(
                        str(value)
                        .replace(f"{schema}.", "<schema>.")
                        .replace(f"{SCHEMA}.", "<schema>.")
                        for value in row
                    )
                    for row in connection.execute(text(query), {"schema": schema, "table": table})
                )
                for kind, query in _CATALOG.items()
            }
    return snapshot


@pytest.mark.database
def test_runtime_metadata_matches_the_revision(disposable_database: str, engine: Engine) -> None:
    """The declared tables, built by SQLAlchemy beside the migrated ones, agree.

    Every constraint (`pg_get_constraintdef`), column (type, nullability,
    default, precision, identity) and index (`pg_get_indexdef`) of the 10 plane
    tables built from `tables.py` into a scratch schema equals the revision's.
    """
    del disposable_database
    command.upgrade(_config(), REVISION)
    parity = "rpt_parity"
    plane = set(PLANE_TABLES)
    copies = MetaData()
    built = [
        table.to_metadata(
            copies,
            schema=parity,
            referred_schema_fn=lambda _t, _s, constraint, referred: (
                parity
                if constraint.elements[0].target_fullname.split(".")[1] in plane
                else referred
            ),
        )
        for table in DECLARED
    ]
    with engine.begin() as connection:
        connection.execute(text(f"CREATE SCHEMA {parity}"))
        copies.create_all(connection, tables=built)
    try:
        migrated = _definitions(engine, SCHEMA, PLANE_TABLES)
        declared = _definitions(engine, parity, PLANE_TABLES)
        for table in PLANE_TABLES:
            for kind in _CATALOG:
                assert migrated[table][kind] == declared[table][kind], (table, kind)
            assert migrated[table]["constraints"], table
    finally:
        with engine.begin() as connection:
            connection.execute(text(f"DROP SCHEMA {parity} CASCADE"))


