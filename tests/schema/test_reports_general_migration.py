    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    _seed_legacy(engine)
    before = _evidence(engine)
    catalog_before = _full_catalog(engine)
    for table in LEGACY_SEEDED:
        assert before[table][0] >= 1, table
    assert not set(before) & _PLANE_QUALIFIED
    command.upgrade(_config(), REVISION)
    assert _version(engine) == REVISION
    after = _evidence(engine)
    assert set(after) - set(before) == _PLANE_QUALIFIED
    for table, evidence in before.items():
        if table == "public.alembic_version":
            continue
        assert after[table] == evidence, table
    for table in _PLANE_QUALIFIED:
        assert after[table][0] == 0, table
    catalog_after = _full_catalog(engine)
    kept = _without_plane(catalog_after)
    for kind in _ALL_CATALOG:
        if kind != "constraints":
            assert kept[kind] == catalog_before[kind], kind
    # Exactly two pre-existing definitions changed: `capability_is_known`,
    # widened by exactly the 15 report capabilities, and `purpose_is_known`,
    # widened by exactly `report_lifecycle`, `report_hold` and `report_retention`.
    removed = sorted(set(catalog_before["constraints"]) - set(kept["constraints"]))
    added = sorted(set(kept["constraints"]) - set(catalog_before["constraints"]))
