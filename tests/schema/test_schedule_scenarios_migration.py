def _offline(target: str, *, down: bool = False) -> str:
    buffer = io.StringIO()
    action = command.downgrade if down else command.upgrade
    action(_config(buffer), target, sql=True)
    return _flat(buffer.getvalue())


_LIVE_REFERENCE: Final = re.compile(
    r"\bknowledge\.(schedule_publications|schedule_series|record_links)\b"
)


def test_live_table_work_is_last_in_the_upgrade(monkeypatch: pytest.MonkeyPatch) -> None:
    """Section 14.6.2: nothing alters a live table before the last trigger on a new one.

    Before step 7, a live table is named only by the early retired-role read
    (step 2) and by the function bodies (step 5), which take no lock.
    """
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{PREVIOUS}:{REVISION}")
    body = rendered[rendered.index(f"Running upgrade {PREVIOUS} -> {REVISION}") :]
    assert body.index("SET LOCAL lock_timeout = '10s'") < body.index(RETIRED)
    assert body.index(RETIRED) < body.index("CREATE TABLE")
    lock = body.index("LOCK TABLE knowledge.schedule_publications IN ACCESS EXCLUSIVE MODE")
    last_trigger = max(body.rindex("CREATE CONSTRAINT TRIGGER"), body.rindex("CREATE TRIGGER "))
    # The only trigger after the lock is G10, on the live table itself.
    assert re.findall(r"CREATE (?:CONSTRAINT )?TRIGGER (\w+)", body[lock:]) == [
        "a_schedule_intake_series_admits_no_other_publication"
    ]
    assert body.rindex("CREATE CONSTRAINT TRIGGER") < lock
    assert body.rindex("CREATE TRIGGER ", 0, lock) < lock < last_trigger
    # The authoritative refusal runs under the lock, before the restatement.
    authoritative = body.index(RETIRED, lock)
    restate = body.index("ALTER TABLE knowledge.schedule_publications DROP CONSTRAINT")
    assert lock < authoritative < restate
    g10 = body.index("CREATE TRIGGER a_schedule_intake_series_admits_no_other_publication")
    first_fk = body.index("ADD CONSTRAINT an_intake_series_is_a_series_of_its_project")
    phase_c = body.index("ALTER TABLE knowledge.record_links")
    assert restate < g10 < first_fk < phase_c
    # Phase C is one statement and the last of the revision.
    assert body.count("ALTER TABLE knowledge.record_links") == 1
    assert phase_c > body.rindex("ADD CONSTRAINT a_schedule_scenario_starts_from_a_publication")
    assert body.index("UPDATE alembic_version SET version_num='2a90f91dd786'") > phase_c
    # Before the lock, a live table appears only in the early read and in
    # function bodies (no `ALTER`, `LOCK` or `FOREIGN KEY` statement).
    head = body[:lock]
    for statement in re.split(r";\s", head):
        if _LIVE_REFERENCE.search(statement):
            assert "ALTER TABLE knowledge.schedule" not in statement.split("REFERENCES")[0] or (
                "schedule_scenarios ADD CONSTRAINT a_schedule_scenario_forks" in statement
            ), statement[:160]
            assert "LOCK TABLE" not in statement, statement[:160]


def test_offline_downgrade_refuses_first(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MY_PA_DATABASE_URL", "postgresql+psycopg://localhost/my_pa")
    rendered = _offline(f"{REVISION}:{PREVIOUS}", down=True)
    refusal = rendered.index(REFUSAL)
    # FR9-F06: the plane is locked before it is checked, so the refusal is authoritative.
    lock = rendered.index("LOCK TABLE knowledge.schedule_intake_series,")
    assert rendered.index("SET LOCAL lock_timeout = '10s'") < lock < refusal
    locked = rendered[lock : rendered.index("IN ACCESS EXCLUSIVE MODE", lock)]
    assert all(f"knowledge.{table}" in locked for table in PLANE_TABLES), locked
    assert rendered.index("DROP TRIGGER") > refusal
    for table in PLANE_TABLES:
        assert rendered.index(f"DROP TABLE knowledge.{table} RESTRICT") > refusal
    last_table = max(
        rendered.index(f"DROP TABLE knowledge.{table} RESTRICT") for table in PLANE_TABLES
    )
    publications = rendered.index("ALTER TABLE knowledge.schedule_publications DROP CONSTRAINT")
    record_links = rendered.index("ALTER TABLE knowledge.record_links DROP CONSTRAINT")
    assert last_table < publications < record_links
    assert f"SET version_num='{PREVIOUS}'" in rendered


