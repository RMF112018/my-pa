class _SeamOp:
    """`op` for one in-process upgrade: after the early refusal, insert a retired row.

    The row lands in the revision's own transaction after step 2's read, so only
    step 7's authoritative refusal (under `ACCESS EXCLUSIVE`) can see it.
    """

    def __init__(self, real: object, early_refusal: str) -> None:
        self._real = real
        self._early_refusal = early_refusal
        self.seamed = False

    def execute(self, statement: str) -> None:
        self._real.execute(statement)  # type: ignore[attr-defined]
        if statement == self._early_refusal and not self.seamed:
            self.seamed = True
            self._real.execute("SET LOCAL session_replication_role = replica")  # type: ignore[attr-defined]
            self._real.execute(  # type: ignore[attr-defined]
                _NEIGHBOUR_SEEDS[1][2]
                .replace(":p", f"'{P}'")
                .replace(":digest", f"'{_DIGEST}'")
                .replace("'update')", "'reference')")
            )
            self._real.execute("SET LOCAL session_replication_role = origin")  # type: ignore[attr-defined]


