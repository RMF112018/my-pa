@pytest.mark.database
@pytest.mark.parametrize("clause", list(_CLAUSES))
def test_downgrade_refuses_while_any_plane_row_exists(
    disposable_database: str, engine: Engine, clause: str
) -> None:
    del disposable_database
    command.upgrade(_config(), "head")
    _seed(engine, _CLAUSES[clause])
    with engine.connect() as connection:
        holding = [
            name
            for name in PLANE_TABLES
            if connection.execute(
                text(f"SELECT EXISTS (SELECT 1 FROM knowledge.{name})")  # noqa: S608
            ).scalar_one()
        ]
    assert holding == ([clause] if clause in _PLANE_SEEDS else [])
    with pytest.raises(DBAPIError) as refused:
        command.downgrade(_config(), PREVIOUS)
    assert getattr(refused.value.orig, "sqlstate", None) == RESTRICT_VIOLATION
    assert REFUSAL in str(refused.value)
    _assert_present(engine)


def _catalog(engine: Engine) -> dict[str, list[str]]:
    """Every constraint, index, trigger, function and relation of the schema, as text."""
    queries = {
        "constraints": (
            "SELECT c.relname || '.' || con.conname || ' ' || pg_get_constraintdef(con.oid) "
            "FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid "
            "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = :schema"
        ),
        "indexes": "SELECT indexdef FROM pg_indexes WHERE schemaname = :schema",
        "triggers": (
            "SELECT c.relname || '.' || t.tgname FROM pg_trigger t JOIN pg_class c "
            "ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = :schema AND NOT t.tgisinternal"
        ),
        "functions": (
            "SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' "
            "FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
            "WHERE n.nspname = :schema"
        ),
        "relations": (
            "SELECT c.relname || ' ' || c.relkind::text FROM pg_class c JOIN pg_namespace n "
            "ON n.oid = c.relnamespace WHERE n.nspname = :schema"
        ),
    }
    with engine.connect() as connection:
        return {
            kind: sorted(connection.execute(text(query), {"schema": SCHEMA}).scalars())
            for kind, query in queries.items()
        }


@pytest.mark.database
def test_clean_downgrade_restores_every_before_text(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    at_previous = _catalog(engine)
    before = {table: _constraint_defs(engine, table) for table in RESTATED}
    command.upgrade(_config(), REVISION)
    at_head = _catalog(engine)
    added = {kind: set(at_head[kind]) - set(at_previous[kind]) for kind in at_head}
    assert {name.split("(")[0] for name in added["functions"]} == set(PLANE_FUNCTIONS)
    for table, names in RESTATED.items():
        changed = {
            name
            for name, definition in _constraint_defs(engine, table).items()
            if before[table].get(name) != definition
        }
        assert changed == set(names), table
    command.downgrade(_config(), PREVIOUS)
    _assert_absent(engine)
    assert _catalog(engine) == at_previous
    for table in RESTATED:
        assert _constraint_defs(engine, table) == before[table], table
    command.upgrade(_config(), REVISION)
    _assert_present(engine)
    assert _catalog(engine) == at_head


