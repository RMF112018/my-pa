def _version(engine: Engine) -> str:
    with engine.connect() as connection:
        return str(connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one())


def _relations(engine: Engine) -> set[str]:
    with engine.connect() as connection:
        return set(
            connection.execute(
                text("SELECT tablename FROM pg_tables WHERE schemaname = :schema"),
                {"schema": SCHEMA},
            ).scalars()
        )


def _functions(engine: Engine) -> set[str]:
    with engine.connect() as connection:
        return set(
            connection.execute(
                text(
                    "SELECT p.proname FROM pg_proc p JOIN pg_namespace n "
                    "ON n.oid = p.pronamespace WHERE n.nspname = :schema"
                ),
                {"schema": SCHEMA},
            ).scalars()
        )


def _constraint_defs(engine: Engine, table: str) -> dict[str, str]:
    with engine.connect() as connection:
        return dict(
            connection.execute(
                text(
                    "SELECT con.conname, pg_get_constraintdef(con.oid) FROM pg_constraint con "
                    "JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n "
                    "ON n.oid = c.relnamespace WHERE n.nspname = :schema AND c.relname = :table"
                ),
                {"schema": SCHEMA, "table": table},
            ).all()
        )


