def test_the_revision_imports_no_package_module() -> None:
    imported: set[str] = set()
    for node in ast.walk(ast.parse(_source())):
        if isinstance(node, ast.ImportFrom) and node.module is not None:
            imported.add(node.module)
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert imported <= {"alembic", "__future__", "typing"}
    assert "my_pa" not in _source()


def test_before_texts_are_byte_copies_and_at_adds_exactly_the_plane_vocabulary() -> None:
    mine = _namespace()
    previous = _namespace(PREVIOUS_MIGRATION)
    assert mine["_CAPABILITIES_BEFORE_THIS_REVISION"] == previous["_CAPABILITIES_AT_THIS_REVISION"]
    assert mine["_PURPOSES_BEFORE_THIS_REVISION"] == previous["_PURPOSES_AT_THIS_REVISION"]
    before = _literals(mine["_CAPABILITIES_BEFORE_THIS_REVISION"])
    at = _literals(mine["_CAPABILITIES_AT_THIS_REVISION"])
    assert at == sorted(at)
    assert (len(before), len(at)) == (266, 292)
    assert set(at) - set(before) == S63_CAPABILITIES
    assert set(before) <= set(at)
    purposes_before = _literals(mine["_PURPOSES_BEFORE_THIS_REVISION"])
    purposes_at = _literals(mine["_PURPOSES_AT_THIS_REVISION"])
    assert purposes_at == sorted(purposes_at)
    assert (len(purposes_before), len(purposes_at)) == (65, 68)
    assert set(purposes_at) - set(purposes_before) == S63_PURPOSES
    refusal = str(mine["_REFUSE_DOWNGRADE"])
    named = {
        literal
        for literal in _literals(refusal)
        if literal != "restrict_violation" and not literal.startswith("schedule scenarios audit")
    }
    assert named == S63_CAPABILITIES | S63_PURPOSES
    assert REFUSAL in refusal


