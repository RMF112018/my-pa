@pytest.mark.database
def test_clean_downgrade_restores_the_before_texts(
    disposable_database: str, engine: Engine
) -> None:
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    before = _checks(engine)
    command.upgrade(_config(), REVISION)
    at_head = _checks(engine)
    assert set(before) == set(at_head) == set(CHECKS)
    for name in CHECKS:
        assert before[name] != at_head[name], name
    assert "'schedule_baselines.set_governing'" in at_head["capability_is_known"]
    assert "'schedule_baseline_approval'" in at_head["purpose_is_known"]
    # Upgraded, a plane name is admitted; an unknown one is still refused.
    _audit(
        engine,
        capability="schedule_cpm_runs.create",
        purpose="schedule_analysis_authoring",
        suffix="s63vocab0003a",
    )
    with pytest.raises(DBAPIError) as unknown:
        _audit(
            engine,
            capability="schedule_scenarios.delete",
            purpose="schedule_analysis_authoring",
            suffix="s63vocab0004a",
        )
    assert getattr(unknown.value.orig, "sqlstate", None) == CHECK_VIOLATION
    with engine.begin() as connection:
        connection.execute(
            text("DELETE FROM knowledge.audit_events WHERE audit_id = 'audit_s63vocab0003a'")
        )
    command.downgrade(_config(), PREVIOUS)
    assert _version(engine) == PREVIOUS
    assert _checks(engine) == before
    with pytest.raises(DBAPIError) as refused:
        _audit(
            engine,
            capability="schedule_cpm_runs.create",
            purpose="status_observation",
            suffix="s63vocab0005a",
        )
    assert getattr(refused.value.orig, "sqlstate", None) == CHECK_VIOLATION
    command.upgrade(_config(), REVISION)
    assert _checks(engine) == at_head


def _run_revision(engine: Engine, step: str) -> str:
    """Run this revision's `upgrade`/`downgrade` on one connection; return its `lock_timeout`."""
    namespace = _namespace()
    with engine.connect() as connection:
        with connection.begin(), Operations.context(MigrationContext.configure(connection)):
            namespace[step]()  # type: ignore[operator]
        return str(connection.execute(text("SHOW lock_timeout")).scalar_one())


@pytest.mark.database
def test_a_held_lock_aborts_the_upgrade_cleanly(disposable_database: str, engine: Engine) -> None:
    """Another session holds `audit_events`: `55P03`, nothing applied; the timeout is local.

    The second half is what `SET LOCAL` buys over `SET`: once the revision
    commits on a connection, that connection's `lock_timeout` is its default
    again (P3-37).
    """
    del disposable_database
    command.upgrade(_config(), PREVIOUS)
    before = _checks(engine)
    holder = engine.connect()
    holding = holder.begin()
    holder.execute(text("LOCK TABLE knowledge.audit_events IN ROW EXCLUSIVE MODE"))
    outcome: list[BaseException | None] = []

    def upgrade() -> None:
        try:
            command.upgrade(_config(), REVISION)
        except BaseException as error:
            outcome.append(error)
        else:
            outcome.append(None)

    worker = threading.Thread(target=upgrade, daemon=True)
    worker.start()
    worker.join(timeout=60)
    timed_out = worker.is_alive()
    holding.rollback()
    holder.close()
    worker.join(timeout=60)
    assert not timed_out, "the upgrade waited past its bounded wait: no lock_timeout"
    assert outcome and isinstance(outcome[0], DBAPIError), outcome
    assert getattr(outcome[0].orig, "sqlstate", None) == LOCK_NOT_AVAILABLE
    assert _version(engine) == PREVIOUS
    assert _checks(engine) == before
    with engine.connect() as connection:
        default = str(connection.execute(text("SHOW lock_timeout")).scalar_one())
    assert default != "10s"
    assert _run_revision(engine, "upgrade") == default
    assert "'schedule_analysis_read'" in _checks(engine)["purpose_is_known"]
    assert _run_revision(engine, "downgrade") == default
    assert _checks(engine) == before


@pytest.mark.database
def test_runtime_metadata_matches_the_revision(disposable_database: str, engine: Engine) -> None:
    """The 2 restated CHECKs equal the `tables.py` declaration built in a scratch schema."""
    del disposable_database
    command.upgrade(_config(), "head")
    parity = "s63_parity"
    copies = MetaData()
    built = tables.METADATA.tables[f"{SCHEMA}.audit_events"].to_metadata(copies, schema=parity)
    with engine.begin() as connection:
        connection.execute(text(f"CREATE SCHEMA {parity}"))
        copies.create_all(connection, tables=[built])
    try:
        assert _checks(engine) == _checks(engine, parity)
        assert set(_checks(engine)) == set(CHECKS)
    finally:
        with engine.begin() as connection:
            connection.execute(text(f"DROP SCHEMA {parity} CASCADE"))


